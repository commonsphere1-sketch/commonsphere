#!/usr/bin/env node
/**
 * Builds src/data/foreignAid.ts - who gives aid and who receives it, as asked: official development assistance, by the
 * OECD's Development Assistance Committee, as the World Bank's World Development Indicators publish it (CC BY 4.0).
 *
 *   Received (DT.ODA.ODAT.CD, DT.ODA.ODAT.PC.ZS, DT.ODA.ODAT.GN.ZS) - net official development assistance and official
 *   aid a country received, in current US dollars, per person and as a share of its gross national income.
 *   Given (DC.ODA.TOTL.CD, DC.ODA.TOTL.GN.ZS) - net official development assistance a donor provided, in current US
 *   dollars, and as a share of its gross national income where the World Bank's figure for that is no more than two years
 *   older than its sum.
 *
 * Every figure is the OECD's, as the World Bank gives it; none is worked out here.
 *
 *   node build-aid.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/foreignAid.ts");
const CACHE = path.join(os.tmpdir(), "commonsphere-aid");
fs.mkdirSync(CACHE, { recursive: true });
const TODAY = new Date().toISOString().slice(0, 10);
const UA = "CommonSphere-build/1.0 (https://commonsphere.vercel.app)";
function get(url, name) {
  const file = path.join(CACHE, name);
  if (!fs.existsSync(file) || Date.now() - fs.statSync(file).mtimeMs > 20 * 3600e3) execFileSync("curl", ["-s", "-L", "--fail", "--max-time", "300", "-A", UA, "-o", file, url]);
  return JSON.parse(fs.readFileSync(file, "utf8"));
}
const SITE = new Set([...fs.readFileSync(path.join(__dirname, "src/data/countriesData.ts"), "utf8").matchAll(/\bcode:\s*"([A-Z]{2})"/g)].map((m) => m[1]));
function series(id) {
  const j = get(`https://api.worldbank.org/v2/country/all/indicator/${id}?format=json&per_page=30000&date=2010:2030`, `${id}.json`);
  if (!Array.isArray(j) || !j[1]) throw new Error(`${id}: an unexpected answer`);
  const out = {};
  for (const d of j[1]) {
    if (d.value === null || !/^[A-Z]{2}$/.test(d.country.id) || !SITE.has(d.country.id)) continue;
    (out[d.country.id] ??= []).push([+d.date, d.value]);
  }
  for (const k of Object.keys(out)) out[k].sort((a, b) => a[0] - b[0]);
  return out;
}
const r2 = (v) => Math.round(v * 100) / 100;

const recv = series("DT.ODA.ODAT.CD");
const recvPc = series("DT.ODA.ODAT.PC.ZS");
const recvGni = series("DT.ODA.ODAT.GN.ZS");
const gave = series("DC.ODA.TOTL.CD");
const gaveGni = series("DC.ODA.TOTL.GN.ZS");

const AID = {};
for (const cc of SITE) {
  const r = recv[cc] ?? [];
  const g = gave[cc] ?? [];
  if (!r.length && !g.length) continue;
  const lastR = r.at(-1);
  const lastG = g.at(-1);
  const gni = gaveGni[cc]?.at(-1);
  AID[cc] = {
    received: r.slice(-10).map(([y, v]) => [y, Math.round(v)]),
    receivedPerPerson: lastR ? (recvPc[cc]?.find(([y]) => y === lastR[0])?.[1] ?? null) : null,
    receivedGni: lastR ? (recvGni[cc]?.find(([y]) => y === lastR[0])?.[1] ?? null) : null,
    given: g.slice(-10).map(([y, v]) => [y, Math.round(v)]),
    givenGni: lastG && gni && lastG[0] - gni[0] <= 2 ? [gni[0], r2(gni[1])] : null,
  };
  if (AID[cc].receivedPerPerson !== null) AID[cc].receivedPerPerson = r2(AID[cc].receivedPerPerson);
  if (AID[cc].receivedGni !== null) AID[cc].receivedGni = r2(AID[cc].receivedGni);
}
const donors = Object.entries(AID).filter(([, a]) => a.given.length).length;
const recipients = Object.entries(AID).filter(([, a]) => a.received.length).length;
if (donors < 20 || recipients < 100) throw new Error(`${donors} donors and ${recipients} recipients`);
const lastRecvYear = Math.max(...Object.values(AID).flatMap((a) => a.received.map(([y]) => y)));
const lastGaveYear = Math.max(...Object.values(AID).flatMap((a) => a.given.map(([y]) => y)));

fs.writeFileSync(
  OUT,
  `/**
 * Official development assistance: what ${recipients} countries received (to ${lastRecvYear}) and ${donors} donors gave (to ${lastGaveYear}), by the OECD's
 * Development Assistance Committee as the World Bank's World Development Indicators publish it (CC BY 4.0).
 *
 * GENERATED by build-aid.cjs on ${TODAY} — do not edit by hand; change the script and re-run it.
 */
export const AID_SOURCES = {
  received: { label: "World Bank WDI — Net official development assistance and official aid received (DT.ODA.ODAT.CD, .PC.ZS, .GN.ZS), from the OECD Development Assistance Committee", url: "https://data.worldbank.org/indicator/DT.ODA.ODAT.CD" },
  given: { label: "World Bank WDI — Net official development assistance provided (DC.ODA.TOTL.CD, DC.ODA.TOTL.GN.ZS), from the OECD Development Assistance Committee", url: "https://data.worldbank.org/indicator/DC.ODA.TOTL.CD" },
  oecd: { label: "OECD — Official development assistance: definition and coverage", url: "https://www.oecd.org/en/topics/official-development-assistance-oda.html" },
};
export type Aid = {
  /** [year, net US$ received] */
  received: [number, number][];
  /** The latest year's, per person (US$) and as a share of gross national income (%). */
  receivedPerPerson: number | null;
  receivedGni: number | null;
  /** [year, net US$ given] */
  given: [number, number][];
  /** [year, % of gross national income] where the World Bank's is near the latest sum's year. */
  givenGni: [number, number] | null;
};
export const FOREIGN_AID: Record<string, Aid> = ${JSON.stringify(AID)};
`,
);
console.log(`wrote ${path.relative(__dirname, OUT)}: ${recipients} recipients to ${lastRecvYear}, ${donors} donors to ${lastGaveYear}`);
console.log(`  samples: UA ${JSON.stringify(AID.UA?.received.at(-1))} per ${AID.UA?.receivedPerPerson} · ET ${JSON.stringify(AID.ET?.received.at(-1))} · US gave ${JSON.stringify(AID.US?.given.at(-1))} gni ${JSON.stringify(AID.US?.givenGni)} · DE ${JSON.stringify(AID.DE?.given.at(-1))} gni ${JSON.stringify(AID.DE?.givenGni)} · NO gni ${JSON.stringify(AID.NO?.givenGni)}`);
