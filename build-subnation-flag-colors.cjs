/**
 * Builds src/data/subnationFlagColors.ts — one colour for each division that
 * has a flag, read off the flag, for the Dashboard's map to light a division
 * in when it is pointed at.
 *
 * The flags are the ones subnations.ts holds: the file each division's
 * Wikidata record names on Wikimedia Commons, already kept only under a
 * licence the site can use. Each is fetched once as a 60-pixel PNG and read
 * by the same decoder and the same rule as a country's flag
 * (build-flag-colors.cjs): the most widespread colour that is a colour - not
 * white, black or grey. A flag that is not a PNG once scaled (a photograph),
 * or that has no such colour, has no entry, and the map falls back to a shade
 * of its country's colour.
 *
 *   node build-subnations.cjs                (first: this reads what it writes)
 *   node build-subnation-flag-colors.cjs     (cached between runs in the system's temp folder)
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const crypto = require("crypto");
const { decodePng, flagColor } = require("./build-flag-colors.cjs");

const OUT = path.join(__dirname, "src/data/subnationFlagColors.ts");
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
const CACHE = path.join(os.tmpdir(), "commonsphere-subnation-flags");
fs.mkdirSync(CACHE, { recursive: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const hash = (s) => crypto.createHash("sha1").update(s).digest("hex").slice(0, 20);

/** The flag at 60 pixels wide, as Commons serves it; null where it will not. */
async function thumb(file) {
  const at = path.join(CACHE, hash(file) + ".bin");
  if (fs.existsSync(at)) return fs.readFileSync(at);
  const url = `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(file.replace(/ /g, "_"))}?width=60`;
  for (let attempt = 0; attempt < 5; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": UA }, signal: AbortSignal.timeout(60000) }).catch((e) => ({ ok: false, status: String(e), headers: new Map() }));
    if (res.ok) {
      const buf = Buffer.from(await res.arrayBuffer());
      fs.writeFileSync(at, buf);
      await sleep(120);
      return buf;
    }
    if (res.status === 404) break;
    // Asked to slow down: wait as long as it says, or longer each time.
    await sleep(1000 * Math.max(Number(res.headers.get?.("retry-after")) || 0, 5 * (attempt + 1)));
  }
  fs.writeFileSync(at, Buffer.alloc(0));
  return Buffer.alloc(0);
}

(async () => {
  const rows = fs
    .readFileSync(path.join(__dirname, "src/data/subnations.ts"), "utf8")
    .split("\n")
    .filter((l) => /^  "\{/.test(l))
    .map((l) => JSON.parse(JSON.parse(l.trim().replace(/,$/, ""))))
    .filter((r) => r.flag);
  const out = {};
  let read = 0;
  let none = 0;
  let done = 0;
  for (const r of rows) {
    const buf = await thumb(r.flag);
    let colour = null;
    try {
      if (buf.length) colour = flagColor(decodePng(buf));
    } catch {
      colour = null;
    }
    if (colour) ((out[r.cc] ??= {})[r.name] = colour), read++;
    else none++;
    if (++done % 300 === 0) console.log(`  flags: ${done} of ${rows.length}`);
  }
  if (read < rows.length * 0.7) throw new Error(`only ${read} of ${rows.length} flags gave a colour`);
  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(
    OUT,
    `/**
 * One colour for each division that has a flag, read off the flag: the most
 * widespread colour in it that is not white, black or grey.
 *
 * GENERATED by build-subnation-flag-colors.cjs on ${today} — do not edit by hand;
 * change the script and re-run it. The flags are the ones subnations.ts
 * holds, from Wikimedia Commons; the rule is build-flag-colors.cjs's. A flag
 * with no such colour has no entry.
 */
export const SUBNATION_FLAG_COLORS_SOURCE = { label: "Division flags: Wikimedia Commons, each under the licence its record names", url: "https://commons.wikimedia.org/", retrieved: "${today}" };

/** By the country's ISO code, then by the division's name as the maps name it. */
export const SUBNATION_FLAG_COLOR: Record<string, Record<string, string>> = {
${Object.entries(out)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([cc, names]) => `  ${cc}: ${JSON.stringify(names)},`)
  .join("\n")}
};
`,
  );
  console.log(`wrote ${path.relative(__dirname, OUT)}: ${read} of ${rows.length} flags gave a colour, ${none} did not`);
  for (const [cc, name] of [["US", "California"], ["US", "Texas"], ["DE", "Bayern"], ["CA", "Québec"], ["JP", "Tokyo"], ["BR", "São Paulo"]]) process.stdout.write(`${cc} ${name} ${out[cc]?.[name]}  `);
  console.log();
})().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
