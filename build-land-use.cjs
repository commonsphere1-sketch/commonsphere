/**
 * Builds src/data/landUse.ts — how each country's land is used, from the
 * World Bank's republication of FAO land-use statistics, with the year.
 *
 * What this replaces. biosphereData.ts gave each country a hand-drawn donut
 * of Forest, Agriculture, Urban, Wetland, Tundra and so on, and any country
 * without one got the same generic default (30% forest, 38% agriculture, 8%
 * urban...) presented as its own. Checked against FAO for 2023, the forest
 * slices were often close - the United States drawn at 33% against 33.9%,
 * Brazil's 59% "rainforest" against 59.0% forest of every kind - but the rest
 * was not: US agriculture 44% against 46.1%, Canada 40% "tundra", a category
 * no statistical body reports as a share of land, and wetland and urban
 * slices that had no source anywhere.
 *
 * Four countries are published with figures that cannot all be right - the
 * Dominican Republic's forest and agricultural land sum to over 100% of its
 * land - and those are left out and listed when the script runs.
 *
 * What it is now. Four slices that add up to the country's land area, all for
 * the same year so they are comparable:
 *
 *   Forest         AG.LND.FRST.ZS
 *   Cropland       AG.LND.ARBL.ZS + AG.LND.CROP.ZS  (arable + permanent crops)
 *   Pasture        AG.LND.AGRI.ZS - cropland        (permanent meadows & pastures)
 *   Other land     the remainder: built-up, bare, ice, shrub, wetland...
 *
 * FAO defines agricultural land as exactly arable land plus permanent crops
 * plus permanent meadows and pastures, and forest as separate from all three,
 * so the subtraction is a definition rather than an estimate. If the numbers
 * ever fail to fit that - a negative pasture, or slices over 100% - the
 * country is dropped and named, rather than drawn wrong.
 *
 *   node build-land-use.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/landUse.ts");
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
const CACHE = path.join(os.tmpdir(), "commonsphere-landuse");
fs.mkdirSync(CACHE, { recursive: true });

const CODES = { forest: "AG.LND.FRST.ZS", agri: "AG.LND.AGRI.ZS", arable: "AG.LND.ARBL.ZS", crops: "AG.LND.CROP.ZS" };

/** iso2 → year → value */
async function series(code) {
  const at = path.join(CACHE, code + ".json");
  if (fs.existsSync(at)) return JSON.parse(fs.readFileSync(at, "utf8"));
  const url = `https://api.worldbank.org/v2/country/all/indicator/${code}?format=json&mrv=8&per_page=25000`;
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${code}: HTTP ${res.status}`);
  const json = await res.json();
  const out = {};
  for (const row of json[1] || []) {
    if (row.value === null || !Number.isFinite(row.value)) continue;
    (out[row.country.id] ||= {})[row.date] = row.value;
  }
  fs.writeFileSync(at, JSON.stringify(out));
  return out;
}

function loadCountries() {
  const bundle = path.join(CACHE, "countriesData.cjs");
  execSync(
    `npx esbuild src/data/countriesData.ts --bundle --format=cjs --platform=node --log-level=error --outfile="${bundle}"`,
    { cwd: __dirname, stdio: "inherit" },
  );
  delete require.cache[bundle];
  return require(bundle).countriesData;
}

const r1 = (v) => Math.round(v * 10) / 10;

(async () => {
  const s = {};
  for (const [k, code] of Object.entries(CODES)) s[k] = await series(code);
  const countries = loadCountries();

  const rows = [];
  const years = {};
  const dropped = [];
  const none = [];
  for (const c of [...countries].sort((a, b) => a.id.localeCompare(b.id))) {
    const f = s.forest[c.code], a = s.agri[c.code], ar = s.arable[c.code], cr = s.crops[c.code];
    if (!f || !a || !ar || !cr) { none.push(c.name); continue; }
    // Latest year all four are published for.
    const year = Object.keys(f).filter((y) => y in a && y in ar && y in cr).sort().pop();
    if (!year) { none.push(c.name); continue; }
    const forest = f[year], crop = ar[year] + cr[year], pasture = a[year] - crop;
    const other = 100 - forest - a[year];
    if (pasture < -0.05 || other < -0.05) {
      dropped.push(`${c.name} (${year}: forest ${forest.toFixed(1)}, agri ${a[year].toFixed(1)}, cropland ${crop.toFixed(1)})`);
      continue;
    }
    years[year] = (years[year] || 0) + 1;
    rows.push(
      `  ${JSON.stringify(c.id)}: { y: "${year}", forest: ${r1(forest)}, cropland: ${r1(crop)}, pasture: ${r1(Math.max(0, pasture))}, other: ${r1(Math.max(0, other))} },`,
    );
  }

  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(
    OUT,
    `/**
 * Land use per country, as a share of land area, for one year.
 *
 * GENERATED by build-land-use.cjs on ${today} — do not edit by hand; change the
 * script and re-run it.
 *
 * FAO land-use statistics as republished by the World Bank:
 *   forest    AG.LND.FRST.ZS
 *   cropland  AG.LND.ARBL.ZS + AG.LND.CROP.ZS (arable land and permanent crops)
 *   pasture   AG.LND.AGRI.ZS less cropland (permanent meadows and pastures)
 *   other     everything else: built-up, bare rock, ice, shrub, wetland...
 * The four add up to 100 (to rounding) and are all for the year given.
 * A country the World Bank does not cover has no entry.
 */
export const LAND_USE_SOURCE = {
  label: "FAO land use, via World Bank",
  url: "https://data.worldbank.org/indicator/AG.LND.FRST.ZS",
  retrieved: "${today}",
};

export interface LandUse {
  y: string;
  forest: number;
  cropland: number;
  pasture: number;
  other: number;
}

export const LAND_USE: Record<string, LandUse> = {
${rows.join("\n")}
};
`,
  );
  console.log(`wrote ${path.relative(__dirname, OUT)}: ${rows.length} countries`);
  console.log("  years: " + Object.entries(years).map(([y, n]) => `${y}=${n}`).join("  "));
  if (dropped.length) console.log("  dropped, figures do not fit FAO's definitions: " + dropped.join("; "));
  console.log("  not covered: " + none.join(", "));
})().catch((e) => { console.error(e); process.exit(1); });
