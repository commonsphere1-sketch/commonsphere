/**
 * The humanitarian crises the United Nations is appealing for now: the year's plans in OCHA's Humanitarian Programme
 * Cycle (HPC Tools, the source of the Financial Tracking Service), read from its public API - public domain, as OCHA
 * publishes the same list on the Humanitarian Data Exchange (CC0).
 *
 * Kept: each country's humanitarian needs and response plan, the flash appeals, and the other plans for one country's
 * crisis (a typhoon's, a flood's) - released, and running past the day it is read. Left out: the regional refugee and
 * migrant response plans, which name the countries hosting people who fled another's crisis, not where the crisis is,
 * and the Global Humanitarian Overview's own entry, which names no country. Nothing is worked out: each plan is given
 * with its name, its kind, its period, its countries and the money it asks for, as OCHA has them. A country is found by
 * the three-letter code OCHA gives it, made two-letter by the World Bank's country list.
 *
 *   node build-humanitarian-plans.cjs
 */
const fs = require("fs");
const path = require("path");
const { syncClock, nowIso } = require("./build-clock.cjs");

const UA = "CommonSphere-build/1.0 (https://commonsphere.vercel.app)";
const OUT = path.join(__dirname, "src/data/humanitarianPlans.ts");
const KINDS = { "Humanitarian needs and response plan": "Response plan", "Flash appeal": "Flash appeal", Other: "Other plan" };

(async () => {
  await syncClock();
  const today = nowIso().slice(0, 10);
  const year = today.slice(0, 4);
  const res = await fetch(`https://api.hpc.tools/v2/public/plan/year/${year}`, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`HPC Tools: HTTP ${res.status}`);
  const all = (await res.json()).data;
  /* Each country's two-letter code from its three-letter one, as the World Bank's country list gives them both - the
     plans give the three-letter code for every country, and the two-letter one for some. */
  const wb = await fetch("https://api.worldbank.org/v2/country?format=json&per_page=400", { headers: { "User-Agent": UA } });
  if (!wb.ok) throw new Error(`World Bank countries: HTTP ${wb.status}`);
  const two = new Map((await wb.json())[1].map((c) => [c.id, c.iso2Code]));
  two.set("XKX", "XK");
  two.set("PSE", "PS");
  if (!Array.isArray(all) || !all.length) throw new Error("HPC Tools: no plans");
  const plans = [];
  const left = [];
  for (const p of all) {
    const v = p.planVersion;
    const type = (p.categories ?? []).find((c) => c.group === "planType")?.name ?? "";
    const countries = (p.locations ?? []).filter((l) => l.adminLevel === 0);
    const codes = countries.map((l) => two.get(l.iso3) ?? null);
    const why =
      !p.isReleased ? "not released"
      : !(type in KINDS) ? type || "no kind"
      : !countries.length ? "no country"
      : type === "Other" && countries.length > 1 ? "more than one country"
      : codes.includes(null) ? `a country with no two-letter code (${countries.map((l) => l.iso3).join(", ")})`
      : v.endDate < today ? `ended ${v.endDate}`
      : null;
    if (why) {
      left.push(`${v.name}: ${why}`);
      continue;
    }
    plans.push({
      id: p.id,
      name: v.name,
      kind: KINDS[type],
      from: v.startDate,
      to: v.endDate,
      countries: codes,
      ...(p.revisedRequirements || p.origRequirements ? { needs: p.revisedRequirements || p.origRequirements } : {}),
    });
  }
  plans.sort((a, b) => a.name.localeCompare(b.name));
  const ts = `/**
 * The humanitarian crises the United Nations is appealing for now: the ${year} plans in OCHA's Humanitarian Programme
 * Cycle that run past ${today} - each country's response plan, the flash appeals, and the other plans for one
 * country's crisis - with the countries each names and the money it asks for, in US dollars.
 *
 * GENERATED by build-humanitarian-plans.cjs on ${today} — do not edit by hand; change the script and re-run it.
 *
 * Left out: the regional refugee and migrant response plans, which name the countries hosting people who fled another's
 * crisis, not where the crisis is. A country with no plan here is not found to be without need.
 */
export const HUMANITARIAN_PLANS_RETRIEVED = "${today}";
export const HUMANITARIAN_PLANS_SOURCE = {
  label: "UN OCHA — Humanitarian Programme Cycle: the year's response plans and flash appeals (HPC Tools and the Financial Tracking Service; public domain)",
  url: "https://fts.unocha.org/plans/overview/${year}",
};
export type HumanitarianPlan = { id: number; name: string; kind: "Response plan" | "Flash appeal" | "Other plan"; from: string; to: string; countries: string[]; needs?: number };
/** Each plan's own page on the Financial Tracking Service. */
export const planUrl = (id: number) => \`https://fts.unocha.org/plans/\${id}/summary\`;
export const HUMANITARIAN_PLANS: HumanitarianPlan[] = [
${plans.map((p) => `  ${JSON.stringify(p)},`).join("\n")}
];
`;
  fs.writeFileSync(OUT, ts);
  console.log(`wrote ${path.relative(__dirname, OUT)}: ${plans.length} plans, ${new Set(plans.flatMap((p) => p.countries)).size} countries`);
  console.log(`left out (${left.length}):\n  ${left.join("\n  ")}`);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
