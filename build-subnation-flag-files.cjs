/**
 * Saves the divisions' flags with the site - static/flags/divisions - and
 * writes src/data/subnationFlagFiles.ts, which says which division has a
 * saved flag and under what file name.
 *
 * The flags are the ones subnations.ts holds: the file each division's record
 * names on Wikimedia Commons, already kept only under a licence the site can
 * use (public domain, CC0, CC BY or CC BY-SA), which each division's window
 * names with a link to the file and its author. Until now a card asked
 * Commons for its flag every time it was drawn, by a redirect; a flag that
 * was slow to come, or did not come, left an empty box. Saved here at 120
 * pixels wide, as Commons scales it, each is served with the page.
 *
 * A flag Commons will not serve, or serves as something that is not an
 * image, is left out of the list, and its card goes on asking Commons.
 *
 *   node build-subnations.cjs               (first: this reads what it writes)
 *   node build-subnation-flag-files.cjs     (cached between runs in the system's temp folder)
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const crypto = require("crypto");

const DIR = path.join(__dirname, "static/flags/divisions");
const OUT = path.join(__dirname, "src/data/subnationFlagFiles.ts");
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
const CACHE = path.join(os.tmpdir(), "commonsphere-subnation-flags-120");
const WIDTH = 120;
fs.mkdirSync(CACHE, { recursive: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const hash = (s) => crypto.createHash("sha1").update(s).digest("hex").slice(0, 20);

/** What kind of image the bytes are, by how they begin; null where they are not one a browser draws. */
function kindOf(buf) {
  if (buf.length < 12) return null;
  if (buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47) return "png";
  if (buf[0] === 0xff && buf[1] === 0xd8) return "jpg";
  if (buf.subarray(0, 3).toString("latin1") === "GIF") return "gif";
  if (buf.subarray(0, 4).toString("latin1") === "RIFF" && buf.subarray(8, 12).toString("latin1") === "WEBP") return "webp";
  return null;
}

/** The flag at 120 pixels wide, as Commons serves it; empty where it will not. */
async function thumb(file) {
  const at = path.join(CACHE, hash(file) + ".bin");
  if (fs.existsSync(at)) return fs.readFileSync(at);
  const url = `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(file.replace(/ /g, "_"))}?width=${WIDTH}`;
  for (let attempt = 0; attempt < 5; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": UA }, signal: AbortSignal.timeout(60000) }).catch((e) => ({ ok: false, status: String(e), headers: new Map() }));
    if (res.ok) {
      const buf = Buffer.from(await res.arrayBuffer());
      fs.writeFileSync(at, buf);
      await sleep(120);
      return buf;
    }
    if (res.status === 404) break;
    // Asked to slow down: wait as long as it says, or longer each time.
    await sleep(1000 * Math.max(Number(res.headers.get?.("retry-after")) || 0, 5 * (attempt + 1)));
  }
  fs.writeFileSync(at, Buffer.alloc(0));
  return Buffer.alloc(0);
}

(async () => {
  const rows = fs
    .readFileSync(path.join(__dirname, "src/data/subnations.ts"), "utf8")
    .split("\n")
    .filter((l) => /^  "\{/.test(l))
    .map((l) => JSON.parse(JSON.parse(l.trim().replace(/,$/, ""))))
    .filter((r) => r.flag);
  fs.rmSync(DIR, { recursive: true, force: true });
  fs.mkdirSync(DIR, { recursive: true });
  const saved = {};
  const names = new Set();
  let bytes = 0;
  let missed = 0;
  let next = 0;
  const work = async () => {
    while (next < rows.length) {
      const r = rows[next++];
      const buf = await thumb(r.flag);
      const kind = kindOf(buf);
      if (!kind) {
        missed++;
        continue;
      }
      // A name made of the division's id: letters, digits and dashes only, and its own.
      let name = `${String(r.id).replace(/[^A-Za-z0-9-]+/g, "_")}.${kind}`;
      if (names.has(name.toLowerCase())) name = `${hash(String(r.id))}.${kind}`;
      names.add(name.toLowerCase());
      fs.writeFileSync(path.join(DIR, name), buf);
      saved[r.id] = name;
      bytes += buf.length;
      if ((Object.keys(saved).length + missed) % 200 === 0) console.log(`${Object.keys(saved).length + missed} of ${rows.length}…`);
    }
  };
  await Promise.all([work(), work(), work()]);
  const ids = Object.keys(saved).sort();
  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(
    OUT,
    `/**
 * The divisions whose flag is saved with the site, and the name of its file
 * in static/flags/divisions: served at /flags/divisions/<name>.
 *
 * GENERATED by build-subnation-flag-files.cjs on ${today} — do not edit by hand;
 * change the script and re-run it.
 *
 * Each is the file its division's record names on Wikimedia Commons, at ${WIDTH}
 * pixels wide as Commons scales it, kept only under a licence the site can
 * use; the division's window names the licence and links to the file and its
 * author. ${ids.length} of the ${rows.length} flags held are saved; one that is not is asked
 * of Commons when it is drawn.
 */
export const SUBNATION_FLAG_FILES_SAVED = "${today}";
export const SUBNATION_FLAG_FILE: Record<string, string> = ${JSON.stringify(Object.fromEntries(ids.map((id) => [id, saved[id]])))};
`,
  );
  console.log(`saved ${ids.length} of ${rows.length} flags, ${(bytes / 1048576).toFixed(1)} MB; ${missed} not served as an image`);
})().catch((e) => {
  console.error("FAILED:", e.message);
  process.exit(1);
});
