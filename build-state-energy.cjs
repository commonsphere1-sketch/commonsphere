/**
 * Builds src/data/stateEnergy.ts — each US state's total energy production
 * and consumption, in TWh, for one year, so the rankings' energy measures
 * cover the states as well as the countries.
 *
 * Source. The US Energy Information Administration's State Energy Data
 * System (SEDS), complete data file (no key needed). Two series, in billion
 * Btu:
 *   TEPRB  total primary energy production
 *   TETCB  total energy consumption
 * converted at 293.07107 TWh per quadrillion Btu - the conversion
 * build-energy.cjs uses for the countries' EIA figures, so a state and a
 * country compare. The year is the latest in which every state and DC has
 * both figures.
 *
 *   node build-state-energy.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");

const OUT = path.join(__dirname, "src/data/stateEnergy.ts");
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
const CACHE = path.join(os.tmpdir(), "commonsphere-energy");
fs.mkdirSync(CACHE, { recursive: true });
const URL = "https://www.eia.gov/state/seds/CDF/Complete_SEDS.csv";
/** 1 quadrillion Btu = 293.07107 TWh, so a billion Btu is a millionth of that. */
const BILLION_BTU_TWH = 293.07107 / 1e6;
const STATES = [
  "AL", "AK", "AZ", "AR", "CA", "CO", "CT", "DE", "DC", "FL", "GA", "HI", "ID", "IL", "IN", "IA", "KS", "KY", "LA", "ME", "MD",
  "MA", "MI", "MN", "MS", "MO", "MT", "NE", "NV", "NH", "NJ", "NM", "NY", "NC", "ND", "OH", "OK", "OR", "PA", "RI", "SC", "SD",
  "TN", "TX", "UT", "VT", "VA", "WA", "WV", "WI", "WY",
];

async function download() {
  const at = path.join(CACHE, "Complete_SEDS.csv");
  if (!fs.existsSync(at)) {
    const res = await fetch(URL, { headers: { "User-Agent": UA }, signal: AbortSignal.timeout(300_000) });
    if (!res.ok) throw new Error(`${URL}: HTTP ${res.status}`);
    fs.writeFileSync(at, Buffer.from(await res.arrayBuffer()));
  }
  return fs.readFileSync(at, "utf8");
}

(async () => {
  const text = await download();
  const want = { TEPRB: {}, TETCB: {} };
  for (const line of text.split(/\r?\n/).slice(1)) {
    const [, msn, st, yr, val] = line.split(",").map((x) => x.replace(/^"|"$/g, ""));
    if (!want[msn] || val === undefined || val === "") continue;
    (want[msn][st] ??= {})[yr] = Number(val);
  }
  const years = [...new Set(Object.values(want.TEPRB).flatMap((y) => Object.keys(y)))].sort().reverse();
  const year = years.find((y) => STATES.every((s) => Number.isFinite(want.TEPRB[s]?.[y]) && Number.isFinite(want.TETCB[s]?.[y])));
  if (!year) throw new Error("SEDS: no year with every state's production and consumption");

  const twh = (v) => {
    const t = v * BILLION_BTU_TWH;
    return t >= 100 ? Math.round(t) : Math.round(t * 10) / 10;
  };
  const rows = STATES.map((s) => `  ${JSON.stringify(s.toLowerCase())}: { totalUseTWh: ${twh(want.TETCB[s][year])}, totalProductionTWh: ${twh(want.TEPRB[s][year])} },`);

  // The US produces around 30,000 TWh a year, and Texas more than it uses; if
  // not, the series or the units have changed.
  const us = want.TEPRB.US?.[year] * BILLION_BTU_TWH;
  const tx = want.TEPRB.TX[year] > want.TETCB.TX[year];
  if (!(us > 25000 && us < 36000 && tx)) throw new Error(`SEDS check failed: US production ${Math.round(us)} TWh, Texas net producer ${tx}`);

  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(
    OUT,
    `/**
 * Total energy production and consumption per US state and DC, in TWh, for
 * ${year}.
 *
 * GENERATED by build-state-energy.cjs on ${today} — do not edit by hand;
 * change the script and re-run it.
 *
 * US EIA State Energy Data System: total primary energy production (TEPRB)
 * and total energy consumption (TETCB), converted from billion Btu at
 * 293.07107 TWh per quadrillion Btu, as the countries' EIA figures are.
 */
export const STATE_ENERGY_SOURCE = {
  label: "US EIA — State Energy Data System",
  url: "https://www.eia.gov/state/seds/",
  retrieved: "${today}",
};

export const STATE_ENERGY_YEAR = ${year};

/** By lowercase state code, as statesData.ts keys them. */
export const STATE_ENERGY: Record<string, { totalUseTWh: number; totalProductionTWh: number }> = {
${rows.join("\n")}
};
`,
  );
  console.log(`wrote ${path.relative(__dirname, OUT)}: ${rows.length - 1} states and DC for ${year} (US production ${Math.round(us)} TWh)`);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
