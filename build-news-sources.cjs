/**
 * Builds src/data/newsSources.ts — every desk the news job reads, for the
 * site's banners to list as their sources. Generated from the job's own
 * FEEDS in supabase/functions/refresh-data/news.ts, so the list the reader
 * sees cannot drift from what the job fetches. Re-run after changing FEEDS.
 *
 *   node build-news-sources.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/newsSources.ts");
const bundle = path.join(os.tmpdir(), "commonsphere-news-sources.cjs");
execSync(
  `npx esbuild supabase/functions/refresh-data/news.ts --bundle --format=cjs --platform=node --log-level=error --outfile="${bundle}"`,
  { cwd: __dirname, stdio: "inherit" },
);
const { FEEDS } = require(bundle);
if (!Array.isArray(FEEDS) || FEEDS.length < 30) throw new Error(`only ${FEEDS?.length} feeds`);

/** The outlet's front page, where the feed's own host is not one a reader would visit. */
const SITE = {
  "feeds.bbci.co.uk": "https://www.bbc.co.uk/news",
  "feeds.npr.org": "https://www.npr.org",
  "rss.dw.com": "https://www.dw.com/en",
  "rss.politico.com": "https://www.politico.com",
  "news.un.org": "https://news.un.org/en/",
  "www.pbs.org": "https://www.pbs.org/newshour",
  "www.abc.net.au": "https://www.abc.net.au/news",
  "www.cbc.ca": "https://www.cbc.ca/news",
};

const rows = FEEDS.map((f) => {
  const host = new URL(f.url).host;
  return { outlet: f.outlet, feed: f.url, site: SITE[host] ?? `https://${host}`, topics: f.topics };
});

fs.writeFileSync(
  OUT,
  `/**
 * Every desk the news job reads: the outlet, the feed it reads, the
 * outlet's site, and the pages the desk serves - for the banners to list as
 * their sources.
 *
 * GENERATED by build-news-sources.cjs on ${new Date().toISOString().slice(0, 10)} from supabase/functions/refresh-data/news.ts
 * — do not edit by hand; re-run the script.
 */
export type NewsSource = { outlet: string; feed: string; site: string; topics: string[] };

export const NEWS_SOURCES: NewsSource[] = [
${rows
  .map(
    (r) =>
      `  { outlet: ${JSON.stringify(r.outlet)}, feed: ${JSON.stringify(r.feed)}, site: ${JSON.stringify(r.site)}, topics: [${r.topics.map((t) => JSON.stringify(t)).join(", ")}] },`,
  )
  .join("\n")}
];
`,
);
console.log(`wrote ${path.relative(__dirname, OUT)}: ${rows.length} desks, ${new Set(rows.map((r) => r.outlet)).size} outlets`);
