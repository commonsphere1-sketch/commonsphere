#!/usr/bin/env node
/**
 * Builds src/data/migration.ts - who has moved to and from each country, as asked: migration, by the bodies that count
 * it, as the World Bank's World Development Indicators publish them (CC BY 4.0):
 *
 *   International migrant stock (SM.POP.TOTL, SM.POP.TOTL.ZS) - the people living in a country who were born in another,
 *   or are citizens of another where birthplace is not recorded, and their share of its people: the UN Population
 *   Division's International Migrant Stock, for 1990 to 2024.
 *   Net migration (SM.POP.NETM) - the people who moved in less those who moved out in a year: the UN's World Population
 *   Prospects, kept to 2023, the last year that is an estimate rather than a projection.
 *   Personal remittances (BX.TRF.PWKR.CD.DT, BM.TRF.PWKR.CD.DT, BX.TRF.PWKR.DT.GD.ZS) - what people working abroad send
 *   home, received and paid, in current US dollars and as a share of GDP: the IMF's balance of payments and the World
 *   Bank's staff estimates.
 *
 * Which countries the migrants come from is not given: the UN's table of origins carries no licence that lets this site
 * carry it.
 *
 *   node build-migration.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/migration.ts");
const CACHE = path.join(os.tmpdir(), "commonsphere-migration");
fs.mkdirSync(CACHE, { recursive: true });
const TODAY = new Date().toISOString().slice(0, 10);
const UA = "CommonSphere-build/1.0 (https://commonsphere.vercel.app)";
const WPP_LAST_ESTIMATE = 2023;
function get(url, name) {
  const file = path.join(CACHE, name);
  if (!fs.existsSync(file) || Date.now() - fs.statSync(file).mtimeMs > 20 * 3600e3) execFileSync("curl", ["-s", "-L", "--fail", "--max-time", "300", "-A", UA, "-o", file, url]);
  return JSON.parse(fs.readFileSync(file, "utf8"));
}
const SITE = new Set([...fs.readFileSync(path.join(__dirname, "src/data/countriesData.ts"), "utf8").matchAll(/\bcode:\s*"([A-Z]{2})"/g)].map((m) => m[1]));

/** Every country's figures for one indicator, year by year: { iso2: [[year, value], ...] } oldest first, and the world's. */
function series(id, from) {
  const j = get(`https://api.worldbank.org/v2/country/all/indicator/${id}?format=json&per_page=30000&date=${from}:2030`, `${id}.json`);
  if (!Array.isArray(j) || !j[1]) throw new Error(`${id}: an unexpected answer`);
  const out = {};
  let world = [];
  for (const d of j[1]) {
    if (d.value === null) continue;
    const cc = d.country.id;
    const row = [+d.date, d.value];
    if (d.countryiso3code === "WLD") world.push(row);
    else if (/^[A-Z]{2}$/.test(cc) && SITE.has(cc)) (out[cc] ??= []).push(row);
  }
  for (const k of Object.keys(out)) out[k].sort((a, b) => a[0] - b[0]);
  world = world.sort((a, b) => a[0] - b[0]);
  return { out, world };
}
const r1 = (v) => Math.round(v * 10) / 10;
const r2 = (v) => Math.round(v * 100) / 100;

const stock = series("SM.POP.TOTL", 1990);
const share = series("SM.POP.TOTL.ZS", 1990);
const net = series("SM.POP.NETM", 2000);
const recv = series("BX.TRF.PWKR.CD.DT", 2010);
const paid = series("BM.TRF.PWKR.CD.DT", 2010);
const recvGdp = series("BX.TRF.PWKR.DT.GD.ZS", 2010);

const MIG = {};
for (const cc of SITE) {
  const s = stock.out[cc] ?? [];
  const sh = share.out[cc] ?? [];
  const n = (net.out[cc] ?? []).filter(([y]) => y <= WPP_LAST_ESTIMATE);
  const rv = recv.out[cc] ?? [];
  const pd = paid.out[cc] ?? [];
  const rg = recvGdp.out[cc] ?? [];
  if (!s.length && !n.length && !rv.length && !pd.length) continue;
  MIG[cc] = {
    // [year, people, share of its people] for each year the UN counts.
    stock: s.map(([y, v]) => [y, Math.round(v), r2(sh.find(([sy]) => sy === y)?.[1] ?? NaN)]).map((r) => (Number.isNaN(r[2]) ? [r[0], r[1], null] : r)),
    net: n.slice(-12).map(([y, v]) => [y, Math.round(v)]),
    received: rv.slice(-10).map(([y, v]) => [y, Math.round(v)]),
    paid: pd.slice(-10).map(([y, v]) => [y, Math.round(v)]),
    receivedGdp: rg.slice(-10).map(([y, v]) => [y, r2(v)]),
  };
}
if (Object.keys(MIG).length < 180) throw new Error(`only ${Object.keys(MIG).length} countries`);
const lastStock = share.world.at(-1);
const WORLD = { stock: stock.world.at(-1), share: lastStock ? [lastStock[0], r2(lastStock[1])] : null, received: recv.world.at(-1) };

fs.writeFileSync(
  OUT,
  `/**
 * Migration for ${Object.keys(MIG).length} countries, as the World Bank's World Development Indicators publish it (CC BY 4.0): the UN's international
 * migrant stock to ${stock.world.at(-1)?.[0]}, the UN's net migration estimates to ${WPP_LAST_ESTIMATE}, and personal remittances by the IMF and the World Bank.
 *
 * GENERATED by build-migration.cjs on ${TODAY} — do not edit by hand; change the script and re-run it.
 */
export const MIGRATION_SOURCES = {
  stock: { label: "World Bank WDI — International migrant stock, total and % of population (SM.POP.TOTL, SM.POP.TOTL.ZS), from the UN Population Division's International Migrant Stock", url: "https://data.worldbank.org/indicator/SM.POP.TOTL.ZS" },
  net: { label: "World Bank WDI — Net migration (SM.POP.NETM), from the UN's World Population Prospects", url: "https://data.worldbank.org/indicator/SM.POP.NETM" },
  remittances: { label: "World Bank WDI — Personal remittances, received and paid (BX.TRF.PWKR.CD.DT, BM.TRF.PWKR.CD.DT), from IMF balance of payments data and World Bank staff estimates", url: "https://data.worldbank.org/indicator/BX.TRF.PWKR.CD.DT" },
  un: { label: "UN Population Division — International Migrant Stock 2024", url: "https://www.un.org/development/desa/pd/content/international-migrant-stock" },
};
/** The last year the UN's net migration is an estimate; later years in its tables are projections, and are not kept. */
export const NET_MIGRATION_LAST = ${WPP_LAST_ESTIMATE};
/** The world's: migrant stock [year, people], its share of the world's people [year, %], and remittances received [year, US$]. */
export const MIGRATION_WORLD = ${JSON.stringify(WORLD)} as { stock: [number, number] | null; share: [number, number] | null; received: [number, number] | null };
export type Migration = {
  /** [year, people born abroad, their share of its people %] */
  stock: [number, number, number | null][];
  /** [year, people in less people out] */
  net: [number, number][];
  /** [year, US$] */
  received: [number, number][];
  paid: [number, number][];
  /** [year, % of GDP] */
  receivedGdp: [number, number][];
};
export const MIGRATION: Record<string, Migration> = ${JSON.stringify(MIG)};
`,
);
console.log(`wrote ${path.relative(__dirname, OUT)}: ${Object.keys(MIG).length} countries; world stock ${JSON.stringify(WORLD.stock)} share ${JSON.stringify(WORLD.share)} remittances ${JSON.stringify(WORLD.received)}`);
console.log(`  samples: US ${JSON.stringify(MIG.US?.stock.at(-1))} net ${JSON.stringify(MIG.US?.net.at(-1))} · AE ${JSON.stringify(MIG.AE?.stock.at(-1))} · IN received ${JSON.stringify(MIG.IN?.received.at(-1))} · MX ${JSON.stringify(MIG.MX?.receivedGdp.at(-1))}`);
