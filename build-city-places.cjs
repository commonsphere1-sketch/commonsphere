/**
 * Builds src/data/cityPlaces.ts — for each city on the Cities page, its
 * Wikipedia article and where it is, so a city's window can show the article's
 * opening and history (components/HistoryPanel) and the maps page can mark the
 * city where it stands.
 *
 * The city data holds a name and a country but no position. The article is
 * the one titled with the city's name, after Wikipedia's own redirects; the
 * position is that article's coordinates. Each is checked before it is kept:
 * the page must exist, must not be a disambiguation page, and must carry
 * coordinates - and where the map's own city layer (static/geo/cities.json)
 * has a city of the same name, the two positions must agree to within 150 km,
 * so a namesake in another country cannot slip through.
 *
 * The article's text is not stored: the window fetches it from Wikipedia when
 * it opens, so it is the article as it stands, under CC BY-SA 4.0.
 *
 *   node build-city-places.cjs
 */
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/cityPlaces.ts");
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
const API = "https://en.wikipedia.org/w/api.php";

/** Cities whose article is not titled with the name the page uses. None is needed today; a redirect settles the rest. */
const TITLES = {};

const src = fs.readFileSync(path.join(__dirname, "src/data/citiesData.ts"), "utf8");
const cities = [...src.matchAll(/id: "([^"]+)", name: "([^"]+)", country: "([^"]+)", countryCode: "([A-Z]{2})"/g)].map((m) => ({ id: m[1], name: m[2], country: m[3] }));
const held = (src.match(/\n    id: "/g) || []).length;
if (!cities.length || cities.length !== held) throw new Error(`read ${cities.length} cities, but the list holds ${held}`);

const get = (params) =>
  JSON.parse(
    execFileSync("curl", ["-sSfL", "-m", "60", "-A", UA, "-G", API, ...Object.entries({ format: "json", formatversion: "2", ...params }).flatMap(([k, v]) => ["--data-urlencode", `${k}=${v}`])], {
      encoding: "utf8",
      maxBuffer: 16 * 1024 * 1024,
    }),
  );

const wanted = cities.map((c) => TITLES[c.id] ?? c.name);
const res = get({ action: "query", prop: "coordinates|pageprops", colimit: "max", ppprop: "disambiguation", redirects: "1", titles: wanted.join("|") });
const redirected = new Map((res.query.redirects || []).map((r) => [r.from, r.to]));
const normalized = new Map((res.query.normalized || []).map((r) => [r.from, r.to]));
const pages = new Map(res.query.pages.map((p) => [p.title, p]));

const layer = JSON.parse(fs.readFileSync(path.join(__dirname, "static/geo/cities.json"), "utf8")).rows;
const plain = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
const km = (a, b) => {
  const rad = Math.PI / 180, dLat = (b[1] - a[1]) * rad, dLon = (b[0] - a[0]) * rad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a[1] * rad) * Math.cos(b[1] * rad) * Math.sin(dLon / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
};

const out = [];
for (const c of cities) {
  let title = TITLES[c.id] ?? c.name;
  title = normalized.get(title) ?? title;
  title = redirected.get(title) ?? title;
  const page = pages.get(title);
  if (!page || page.missing) throw new Error(`${c.name}: no Wikipedia article "${title}"`);
  if (page.pageprops && "disambiguation" in page.pageprops) throw new Error(`${c.name}: "${title}" is a disambiguation page - name the article in TITLES`);
  const at = (page.coordinates || []).find((x) => x.primary) ?? (page.coordinates || [])[0];
  if (!at) throw new Error(`${c.name}: "${title}" carries no coordinates`);
  const lon = Math.round(at.lon * 10000) / 10000, lat = Math.round(at.lat * 10000) / 10000;
  // The same name on the map's own layer, nearest first: it must be this place.
  const same = layer.filter((r) => plain(r[0]) === plain(c.name)).map((r) => km([lon, lat], [r[3], r[4]])).sort((a, b) => a - b);
  if (same.length && same[0] > 150) throw new Error(`${c.name}: "${title}" is ${Math.round(same[0])} km from the map layer's ${c.name} - a namesake?`);
  console.log(`  ${c.name.padEnd(24)} ${title.padEnd(26)} ${String(lat).padStart(9)}, ${String(lon).padStart(9)}  ${same.length ? Math.round(same[0]) + " km from the map layer" : "not on the map layer by this name"}`);
  out.push(`  ${JSON.stringify(c.id)}: { wiki: ${JSON.stringify(title)}, lon: ${lon}, lat: ${lat} },`);
}

const today = new Date().toISOString().slice(0, 10);
fs.writeFileSync(
  OUT,
  `/**
 * Each city on the Cities page: its Wikipedia article and where it is.
 *
 * GENERATED by build-city-places.cjs on ${today} — do not edit by hand;
 * change the script and re-run it.
 *
 * The position is the article's own coordinates, checked against the map's
 * city layer where that has the city by the same name.
 */
export const CITY_PLACES_SOURCE = {
  label: "Wikipedia — the coordinates of each city's article",
  url: "https://en.wikipedia.org/",
  retrieved: "${today}",
};

/** City id → the title of its Wikipedia article, and its longitude and latitude. */
export const CITY_PLACES: Record<string, { wiki: string; lon: number; lat: number }> = {
${out.join("\n")}
};
`,
);
console.log(`wrote ${path.relative(__dirname, OUT)}: ${out.length} cities`);
