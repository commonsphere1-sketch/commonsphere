/**
 * Builds src/data/stateHealthSafety.ts - how long people live in each US
 * state and how many die by homicide there: the two figures of health and
 * safety the site holds by state, beside the Census Bureau's and the other
 * bureaus' in stateIndicators.ts.
 *
 *   node build-state-health-safety.cjs
 *
 * Sources - both works of the United States government, in the public domain:
 *
 *   CDC, National Center for Health Statistics - U.S. State Life Expectancy
 *   by Sex, 2021
 *     https://data.cdc.gov/d/it4f-frdc - life expectancy at birth from the
 *     complete period life tables of each state and the District of
 *     Columbia; the figure for both sexes together is kept.
 *
 *   CDC, National Center for Injury Prevention and Control - Mapping Injury,
 *   Overdose, and Violence, state file
 *     https://data.cdc.gov/d/fpsi-y8tj - deaths by homicide to 100,000
 *     residents, by state of residence, from the National Vital Statistics
 *     System. The last whole year in the file is kept, not its running
 *     twelve months, which are provisional.
 *
 * Nothing is worked out. A state whose rate the CDC withholds - too few
 * deaths to publish - has none here.
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/stateHealthSafety.ts");
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
const CACHE = path.join(os.tmpdir(), "commonsphere-state-living");
fs.mkdirSync(CACHE, { recursive: true });

function json(url, name) {
  const at = path.join(CACHE, name);
  if (!fs.existsSync(at)) {
    try {
      execFileSync("curl", ["-sSfL", "-m", "180", "-A", UA, "-o", at, url], { stdio: ["ignore", "ignore", "pipe"] });
    } catch {
      fs.rmSync(at, { force: true });
      throw new Error(`${url}: could not be fetched`);
    }
  }
  return JSON.parse(fs.readFileSync(at, "utf8"));
}

/* The fifty states and the District of Columbia, as the site names them. */
const names = new Set(
  fs
    .readFileSync(path.join(__dirname, "src/data/statesData.ts"), "utf8")
    .split("\n")
    .map((l) => /^\s{4}name: "([^"]+)",$/.exec(l)?.[1])
    .filter(Boolean),
);
if (names.size < 50) throw new Error(`only ${names.size} states were read from statesData.ts`);

/* ── Life expectancy at birth, both sexes ── */
const LIFE_YEAR = 2021;
const life = {};
for (const r of json("https://data.cdc.gov/resource/it4f-frdc.json?$limit=500", "life-2021.json")) {
  if (r.sex !== "Total" || !names.has(r.area)) continue;
  const v = Number(r.leb);
  if (!Number.isFinite(v) || v < 60 || v > 90) throw new Error(`life expectancy of ${r.area}: ${r.leb} is not a life expectancy`);
  life[r.area] = v;
}
if (Object.keys(life).length < 50) throw new Error(`life expectancy: only ${Object.keys(life).length} states`);

/* ── Deaths by homicide to 100,000 residents: the last whole year ── */
const rows = json("https://data.cdc.gov/resource/fpsi-y8tj.json?intent=All_Homicide&$limit=5000", "homicide.json");
const years = [...new Set(rows.map((r) => r.period).filter((p) => /^\d{4}$/.test(p)))].sort();
const HOMICIDE_YEAR = Number(years[years.length - 1]);
if (!(HOMICIDE_YEAR >= 2023)) throw new Error("the homicide file has no recent whole year");
const homicide = {};
for (const r of rows) {
  if (r.period !== String(HOMICIDE_YEAR) || !names.has(r.name)) continue;
  const v = Number(r.rate);
  if (r.rate == null || r.rate === "" || !Number.isFinite(v)) continue; // withheld
  if (v < 0 || v > 60) throw new Error(`homicide rate of ${r.name}: ${r.rate} is not a rate`);
  homicide[r.name] = Number(v.toFixed(1));
}
if (Object.keys(homicide).length < 40) throw new Error(`homicide: only ${Object.keys(homicide).length} states have a rate`);

const today = new Date().toISOString().slice(0, 10);
const table = (o) =>
  Object.keys(o)
    .sort()
    .map((k) => `  ${JSON.stringify(k)}: ${o[k]},`)
    .join("\n");
fs.writeFileSync(
  OUT,
  `/**
 * How long people live in each US state, and how many die by homicide there:
 * the figures of health and safety the site holds by state.
 *
 * GENERATED by build-state-health-safety.cjs on ${today} — do not edit by hand;
 * change the script and re-run it.
 *
 * Both are the CDC's own figures, in the public domain; nothing is worked
 * out. A state whose homicide rate the CDC withholds has none here.
 */
export const STATE_HEALTH_SAFETY_RETRIEVED = "${today}";

export const STATE_HEALTH_SAFETY_SOURCES = {
  life: { label: "CDC, National Center for Health Statistics — U.S. State Life Expectancy by Sex, ${LIFE_YEAR} (public domain)", url: "https://data.cdc.gov/d/it4f-frdc", year: ${LIFE_YEAR} },
  homicide: { label: "CDC — Mapping Injury, Overdose, and Violence, state file, ${HOMICIDE_YEAR} (public domain)", url: "https://data.cdc.gov/d/fpsi-y8tj", year: ${HOMICIDE_YEAR} },
};

/** Life expectancy at birth, in years, both sexes together: by the state's name. */
export const STATE_LIFE_EXPECTANCY: Record<string, number> = {
${table(life)}
};

/** Deaths by homicide to 100,000 residents, by state of residence: by the state's name. */
export const STATE_HOMICIDE: Record<string, number> = {
${table(homicide)}
};
`,
);
console.log(`life expectancy ${LIFE_YEAR}: ${Object.keys(life).length} states; homicide ${HOMICIDE_YEAR}: ${Object.keys(homicide).length} states`);
