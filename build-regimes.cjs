#!/usr/bin/env node
/**
 * Builds src/data/regimes.ts - each country's political regime, for the World Maps page's Governance layer, as asked: the
 * democracies and the autocracies of the world, every country in its type.
 *
 *   V-Dem's Regimes of the World (Lührmann, Tannenberg and Lindberg, 2018), as Our World in Data publishes it (V-Dem 2026,
 *   CC BY-SA; Our World in Data's processing CC BY). Each country's latest year, in one of four types:
 *     0 closed autocracy      - no multi-party elections for the chief executive or the legislature (one-party states,
 *                               absolute monarchies, military rule among them)
 *     1 electoral autocracy   - multi-party elections, without the freedoms that make them free and fair
 *     2 electoral democracy   - free and fair multi-party elections
 *     3 liberal democracy     - those, with the rule of law and limits on the executive besides
 *   The classification uses no word such as "totalitarian" or "dictatorship"; the page gives V-Dem's own four, in its words.
 *
 * Our World in Data gives countries by ISO 3166 alpha-3 code; the World Bank's list of countries gives each one's alpha-2.
 * Its codes for historical states are left out, and so are Somaliland and Zanzibar, which V-Dem scores apart from the
 * countries the site holds them in.
 *
 *   node build-regimes.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/regimes.ts");
const CACHE = path.join(os.tmpdir(), "commonsphere-regimes");
fs.mkdirSync(CACHE, { recursive: true });
const TODAY = new Date().toISOString().slice(0, 10);

function get(url, name) {
  const file = path.join(CACHE, name);
  if (!fs.existsSync(file) || Date.now() - fs.statSync(file).mtimeMs > 20 * 3600e3) execFileSync("curl", ["-s", "-L", "--fail", "--max-time", "180", "-o", file, url]);
  return fs.readFileSync(file, "utf8");
}

const csv = get("https://ourworldindata.org/grapher/political-regime.csv?v=1&csvType=full&useColumnShortNames=true", "political-regime.csv");
const meta = JSON.parse(get("https://ourworldindata.org/grapher/political-regime.metadata.json?v=1&csvType=full&useColumnShortNames=true", "political-regime.meta.json"));
const wb = JSON.parse(get("https://api.worldbank.org/v2/country?format=json&per_page=400", "wb-countries.json"))[1];
const iso2 = new Map(wb.map((c) => [c.id, c.iso2Code]));
iso2.set("OWID_KOS", "XK");
iso2.set("TWN", "TW");

const SITE = new Set();
{
  const src = fs.readFileSync(path.join(__dirname, "src/data/countriesData.ts"), "utf8");
  for (const m of src.matchAll(/\bcode:\s*"([A-Z]{2})"/g)) SITE.add(m[1]);
}

const [head, ...rows] = csv.trim().split(/\r?\n/);
const cols = head.split(",");
const at = (name) => cols.indexOf(name);
const [iCode, iYear, iVal] = [at("code"), at("year"), at("regime_row_owid")];
if (iCode < 0 || iYear < 0 || iVal < 0) throw new Error(`unexpected columns: ${head}`);
const latest = new Map(); // iso2 -> [regime, year]
const skipped = new Set();
for (const line of rows) {
  // The entity's name may hold a comma inside quotes; the last three fields never do.
  const f = line.split(",");
  const code = f[f.length - 3];
  const year = +f[f.length - 2];
  const v = f[f.length - 1];
  if (v === "" || !Number.isFinite(year)) continue;
  const cc = iso2.get(code);
  if (!cc || !SITE.has(cc)) {
    skipped.add(code);
    continue;
  }
  const r = +v;
  if (![0, 1, 2, 3].includes(r)) throw new Error(`${code} ${year}: ${v}`);
  const prev = latest.get(cc);
  if (!prev || year > prev[1]) latest.set(cc, [r, year]);
}
// Only a current figure: a series that stopped long ago - "Palestine" under the British Mandate, to 1948 - is not today's regime.
const lastYear = Math.max(...[...latest.values()].map((x) => x[1]));
const stale = [...latest].filter(([, x]) => x[1] < lastYear - 1);
for (const [cc] of stale) latest.delete(cc);
if (stale.length) console.log(`  left out, their latest figure years old: ${stale.map(([cc, x]) => `${cc} (${x[1]})`).join(", ")}`);
if (latest.size < 150) throw new Error(`only ${latest.size} countries read`);
const counts = [0, 1, 2, 3].map((r) => [...latest.values()].filter((x) => x[0] === r).length);
const years = [...new Set([...latest.values()].map((x) => x[1]))].sort();

fs.writeFileSync(
  OUT,
  `/**
 * Each country's political regime, by V-Dem's Regimes of the World (Lührmann, Tannenberg and Lindberg, 2018), as Our World
 * in Data publishes it (${meta.chart?.citation ?? "V-Dem"}, CC BY-SA; Our World in Data's processing CC BY): ${latest.size} countries, each in its
 * latest year (${years.join(", ")}) - ${counts[0]} closed autocracies, ${counts[1]} electoral autocracies, ${counts[2]} electoral democracies and ${counts[3]} liberal democracies.
 *
 * GENERATED by build-regimes.cjs on ${TODAY} — do not edit by hand; change the script and re-run it.
 */
export const REGIME_SOURCE = { label: "V-Dem — Regimes of the World (Lührmann, Tannenberg & Lindberg), via Our World in Data", url: "https://ourworldindata.org/grapher/political-regime" };
/** The four types, by their score: what V-Dem calls each, and what it means, in its terms. */
export const REGIME_TYPES = [
  { name: "Closed autocracy", said: "No multi-party elections for the chief executive or the legislature" },
  { name: "Electoral autocracy", said: "Multi-party elections, without the freedoms that make them free and fair" },
  { name: "Electoral democracy", said: "Free and fair multi-party elections" },
  { name: "Liberal democracy", said: "Free and fair elections, with the rule of law and limits on the executive" },
] as const;
/** Each country's type (0-3, as REGIME_TYPES) and the year it is for, by ISO 3166-1 alpha-2 code. */
export const REGIMES: Record<string, [regime: 0 | 1 | 2 | 3, year: number]> = ${JSON.stringify(Object.fromEntries([...latest].sort()))};
`,
);
console.log(`wrote ${path.relative(__dirname, OUT)}: ${latest.size} countries (${counts.join(" / ")}), years ${years.join(", ")}`);
console.log(`  not the site's: ${[...skipped].filter((c) => !/^OWID_(BAD|BAV|DRV|GDR|GFR|HAN|HSE|HSG|MEC|MOD|PMA|RVN|SAX|SIC|TUS|YAR|YPR)$/.test(c)).join(" ")}`);
