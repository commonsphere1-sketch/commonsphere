/**
 * Builds src/data/airQuality.ts — the world map's air-pollution layer.
 *
 * Source: World Bank indicator EN.ATM.PM25.MC.M3, "PM2.5 air pollution, mean
 * annual exposure (micrograms per cubic meter)". The World Bank defines it as
 * population-weighted: the average exposure of a nation's population, weighting
 * mean annual PM2.5 concentrations by where people actually live.
 *
 * That definition is the whole caveat for this layer, and the page repeats it.
 * A country shaded here is not a country that is uniformly polluted; it is one
 * national number, and the air over an empty desert in the same country counts
 * for little because few people breathe it. The layer says where people are
 * exposed, not where the pollution sits.
 *
 * The bands are the WHO thresholds as the World Bank states them in the
 * definitions of its companion indicators, checked rather than remembered:
 *
 *   EN.ATM.PM25.MC.ZS     guideline value        10 ug/m3
 *   EN.ATM.PM25.MC.T3.ZS  interim target 3       15 ug/m3
 *   EN.ATM.PM25.MC.T2.ZS  interim target 2       25 ug/m3
 *   EN.ATM.PM25.MC.T1.ZS  interim target 1       35 ug/m3
 *
 * WHO's own fact sheet on ambient air quality independently names interim
 * target one as 35 ug/m3. Nothing here is interpolated: a country the World
 * Bank has no figure for is absent, and the map leaves it unshaded.
 *
 *   node build-air-quality.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/airQuality.ts");
const INDICATOR = "EN.ATM.PM25.MC.M3";
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
const CACHE = path.join(os.tmpdir(), "commonsphere-air-quality");
fs.mkdirSync(CACHE, { recursive: true });

function loadCountries() {
  const bundle = path.join(CACHE, "countriesData.cjs");
  execSync(
    `npx esbuild src/data/countriesData.ts --bundle --format=cjs --platform=node --log-level=error --outfile="${bundle}"`,
    { cwd: __dirname, stdio: "inherit" },
  );
  delete require.cache[bundle];
  return require(bundle).countriesData;
}

(async () => {
  const countries = loadCountries();
  const url = `https://api.worldbank.org/v2/country/all/indicator/${INDICATOR}?format=json&mrv=4&per_page=25000`;
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`World Bank: HTTP ${res.status}`);
  const json = await res.json();
  if (!Array.isArray(json) || !json[1]) throw new Error("World Bank returned no rows");

  // Most recent year the World Bank actually reports for each country.
  const latest = new Map();
  for (const row of json[1]) {
    if (row.value === null || !/^\d{4}$/.test(String(row.date))) continue;
    if (!Number.isFinite(row.value) || row.value < 0) continue;
    const prev = latest.get(row.country.id);
    if (!prev || +row.date > +prev.year) latest.set(row.country.id, { v: row.value, year: row.date });
  }

  const have = countries.filter((c) => latest.has(c.code));
  const missing = countries.filter((c) => !latest.has(c.code));
  if (!have.length) throw new Error("no dataset country matched the indicator");

  const years = [...new Set(have.map((c) => latest.get(c.code).year))].sort();
  const body = have
    .slice()
    .sort((a, b) => a.code.localeCompare(b.code))
    .map((c) => {
      const { v, year } = latest.get(c.code);
      return `  ${c.code}: { pm25: ${Number(v.toFixed(1))}, year: "${year}" },`;
    })
    .join("\n");

  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(
    OUT,
    `/**
 * Population-weighted mean annual PM2.5 exposure, by country.
 *
 * GENERATED by build-air-quality.cjs on ${today} — do not edit by hand; change
 * the script and re-run it.
 *
 * Source: World Bank indicator ${INDICATOR}, "PM2.5 air pollution, mean annual
 * exposure (micrograms per cubic meter)", ${years.join(" and ")} data.
 *
 * Read it as exposure, not geography. The figure is population-weighted, so it
 * describes the air the people of a country breathe on average, not the air
 * over its territory: a large clean emptiness barely moves the number because
 * almost nobody is standing in it. Shading a whole country one colour is what
 * a single national figure supports, and no more than that.
 *
 * ${have.length} of the dataset's ${countries.length} countries have a figure. The other ${missing.length}
 * are absent${missing.length ? ` (${missing.map((c) => c.code).join(", ")})` : ""} and the map leaves them unshaded rather than guessing.
 */
export const AIR_QUALITY_SOURCE = {
  label: "World Bank — PM2.5 mean annual exposure (population-weighted)",
  url: "https://data.worldbank.org/indicator/${INDICATOR}",
  retrieved: "${today}",
  years: "${years.join(", ")}",
};

/**
 * WHO thresholds for annual mean PM2.5, in micrograms per cubic metre, as the
 * World Bank states them in the definitions of its companion indicators
 * (EN.ATM.PM25.MC.ZS and the T1-T3 series). WHO's ambient air quality fact
 * sheet independently names interim target 1 as 35.
 */
export const PM25_THRESHOLDS = {
  guideline: 10,
  interimTarget3: 15,
  interimTarget2: 25,
  interimTarget1: 35,
} as const;

/** The bands the map draws, lowest first. \`upTo\` is null for the open top band. */
export const PM25_BANDS: { label: string; upTo: number | null }[] = [
  { label: "At or below the WHO guideline (10)", upTo: PM25_THRESHOLDS.guideline },
  { label: "Above the guideline, within interim target 3 (15)", upTo: PM25_THRESHOLDS.interimTarget3 },
  { label: "Above interim target 3, within target 2 (25)", upTo: PM25_THRESHOLDS.interimTarget2 },
  { label: "Above interim target 2, within target 1 (35)", upTo: PM25_THRESHOLDS.interimTarget1 },
  { label: "Above interim target 1 (over 35)", upTo: null },
];

export type AirQuality = { pm25: number; year: string };

export const AIR_QUALITY: Record<string, AirQuality> = {
${body}
};

/** Which band a reading falls in, as an index into PM25_BANDS. */
export function pm25Band(pm25: number): number {
  for (let i = 0; i < PM25_BANDS.length; i++) {
    const cap = PM25_BANDS[i].upTo;
    if (cap === null || pm25 <= cap) return i;
  }
  return PM25_BANDS.length - 1;
}
`,
  );

  const counts = [0, 0, 0, 0, 0];
  const caps = [10, 15, 25, 35, Infinity];
  for (const c of have) {
    const v = latest.get(c.code).v;
    counts[caps.findIndex((cap) => v <= cap)]++;
  }
  console.log(`wrote ${path.relative(__dirname, OUT)}`);
  console.log(`  ${have.length} of ${countries.length} countries; years ${years.join(", ")}`);
  console.log(`  missing (${missing.length}): ${missing.map((c) => c.code).join(", ") || "none"}`);
  console.log(`  bands  <=10: ${counts[0]}  <=15: ${counts[1]}  <=25: ${counts[2]}  <=35: ${counts[3]}  >35: ${counts[4]}`);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
