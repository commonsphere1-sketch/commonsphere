#!/usr/bin/env node
/**
 * The political ideas the compass's legend places that the site's record of political ideas (politicalTheories.ts) does
 * not hold, as asked - centrism among them - each described the same way: the opening of its English Wikipedia article,
 * the one of its reference works whose words may be reused, and the entries Wikidata records for it in the Encyclopaedia
 * Britannica (P1417), the Stanford Encyclopedia of Philosophy (P3123) and the Internet Encyclopedia of Philosophy
 * (P5088), to read. An idea with none of the three is given with its Wikidata record beside its article, and the compass
 * says that no encyclopedia entry is recorded for it - so that Wikipedia never stands alone.
 *
 * Writes src/data/compassMoreIdeas.ts. Where each idea is placed on the grid is in compassIdeologies.ts.
 *
 *   node build-compass-ideas.cjs
 */
const fs = require("fs");
const path = require("path");

const UA = "CommonSphere-build/1.0 (https://commonsphere.vercel.app)";
const OUT = path.join(__dirname, "src/data/compassMoreIdeas.ts");
// Their English Wikipedia titles.
const TITLES = [
  "Centrism", "Libertarianism", "Anarcho-capitalism", "Anarcho-syndicalism", "Libertarian socialism", "Minarchism", "Market socialism",
  "Green politics", "Eco-socialism", "Objectivism", "Georgism", "Distributism", "Absolute monarchy", "Social conservatism",
  "Fiscal conservatism", "Liberal conservatism", "National conservatism", "Ordoliberalism", "State socialism", "Stalinism",
  "Marxism–Leninism", "Ba'athism", "Laissez-faire", "Keynesian economics", "Capitalism", "Autocracy", "Plutocracy", "Agorism",
  "Left communism", "Council communism", "Right-libertarianism", "Left-libertarianism",
];

async function qlever(query) {
  const res = await fetch("https://qlever.dev/api/wikidata", {
    method: "POST",
    headers: { "User-Agent": UA, Accept: "application/sparql-results+json", "Content-Type": "application/x-www-form-urlencoded" },
    body: `query=${encodeURIComponent(query)}`,
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`QLever ${res.status}: ${text.slice(0, 300)}`);
  return JSON.parse(text).results.bindings;
}

(async () => {
  const values = TITLES.map((t) => `"${t.replace(/"/g, '\\"')}"@en`).join(" ");
  const rows = await qlever(`PREFIX schema: <http://schema.org/>
PREFIX wdt: <http://www.wikidata.org/prop/direct/>
SELECT ?title ?item ?brit ?sep ?iep WHERE {
  VALUES ?title { ${values} }
  ?article schema:about ?item ; schema:isPartOf <https://en.wikipedia.org/> ; schema:name ?title .
  OPTIONAL { ?item wdt:P1417 ?brit }
  OPTIONAL { ?item wdt:P3123 ?sep }
  OPTIONAL { ?item wdt:P5088 ?iep }
}`);
  const refs = {};
  for (const r of rows) {
    const t = r.title.value;
    const at = (refs[t] ||= { item: r.item.value.split("/").pop(), brit: new Set(), sep: new Set(), iep: new Set() });
    if (r.brit) at.brit.add(r.brit.value);
    if (r.sep) at.sep.add(r.sep.value);
    if (r.iep) at.iep.add(r.iep.value);
  }
  const out = [];
  const left = [];
  for (const title of TITLES) {
    const r = refs[title];
    const sources = [];
    if (r) {
      for (const b of r.brit) sources.push({ label: "Encyclopaedia Britannica", url: `https://www.britannica.com/${b}` });
      for (const s of r.sep) sources.push({ label: "Stanford Encyclopedia of Philosophy", url: `https://plato.stanford.edu/entries/${s}/` });
      for (const i of r.iep) sources.push({ label: "Internet Encyclopedia of Philosophy", url: `https://iep.utm.edu/${i}/` });
    }
    if (!r) {
      left.push(title);
      continue;
    }
    // No encyclopedia entry recorded: its Wikidata record and its article stand together, and the compass says so.
    const bare = !sources.length;
    const sum = await fetch(`https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(title.replace(/ /g, "_"))}`, { headers: { "User-Agent": UA } });
    if (!sum.ok) throw new Error(`${title}: Wikipedia ${sum.status}`);
    const j = await sum.json();
    if (!j.extract) throw new Error(`${title}: no opening`);
    sources.push({ label: `Wikidata — its record, ${r.item} (CC0)`, url: `https://www.wikidata.org/wiki/${r.item}` });
    sources.push({ label: `Wikipedia — ${title}`, url: `https://en.wikipedia.org/wiki/${encodeURIComponent(title.replace(/ /g, "_"))}` });
    out.push({ name: title, said: j.extract.replace(/\s+/g, " ").trim(), sources, ...(bare ? { noEncyclopedia: true } : {}) });
  }
  const bareN = out.filter((o) => o.noEncyclopedia).length;
  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(
    OUT,
    `/**
 * The political ideas the compass's legend places that the site's record of political ideas does not hold, each described
 * the same way: the opening of its English Wikipedia article, with the reference works' entries Wikidata records for it.
 *
 * GENERATED by build-compass-ideas.cjs on ${today} - do not edit by hand; change the script and re-run it.
 * ${out.length} held; ${bareN} of them (\`noEncyclopedia\`) have no entry in the Encyclopaedia Britannica, the Stanford
 * Encyclopedia of Philosophy or the Internet Encyclopedia of Philosophy recorded in Wikidata, and are given with their
 * Wikidata record beside the article.${left.length ? ` Left out, with no English article found: ${left.join(", ")}.` : ""}
 */
export const COMPASS_MORE_IDEAS: { name: string; said: string; sources: { label: string; url: string }[]; noEncyclopedia?: true }[] = ${JSON.stringify(out, null, 2)};
`,
  );
  console.log(`${out.length} ideas held, ${bareN} with no encyclopedia entry recorded; left out: ${left.join(", ") || "none"}`);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
