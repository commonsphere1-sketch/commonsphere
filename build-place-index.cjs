/**
 * Builds src/data/placeIndex.ts — which country profile and which economy
 * card the site holds for each country, by ISO code, so that a window on one
 * page can link to the same place's window on another without loading the
 * page's whole data to find it.
 *
 * A country's profile is found by its code. Its economy card is the one the
 * Economies page itself pairs with it: the card carrying the same ISO code,
 * or, for the cards written before codes were kept, the card with the
 * country's own name. A card of a bloc or a region belongs to no one country
 * and is left out. Nothing is copied but ids.
 *
 *   node build-place-index.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/placeIndex.ts");
const CACHE = path.join(os.tmpdir(), "commonsphere-place-index");
fs.mkdirSync(CACHE, { recursive: true });

function load(file, name) {
  const bundle = path.join(CACHE, `${name}.cjs`);
  execSync(`npx esbuild ${file} --bundle --format=cjs --platform=node --log-level=error --outfile="${bundle}"`, { cwd: __dirname, stdio: "inherit" });
  delete require.cache[bundle];
  return require(bundle)[name];
}
const countries = load("src/data/countriesData.ts", "countriesData");
const economies = load("src/data/economiesData.ts", "economiesData");

const countryOf = {};
for (const c of countries) {
  if (!/^[A-Z]{2}$/.test(c.code || "")) continue;
  if (countryOf[c.code]) throw new Error(`two countries carry the code ${c.code}: ${countryOf[c.code]} and ${c.id}`);
  countryOf[c.code] = c.id;
}

/** Economy cards whose name is not the country profile's: the card says "Turkey" and "Czechia", the profile "Türkiye" and "Czech Republic". */
const SAME_PLACE = { "turkey-eco": "TR", "czechia-eco": "CZ" };

const economyOf = {};
const unmatched = [];
for (const e of economies) {
  if (e.entityType !== "Country" && e.entityType !== "Territory") continue;
  const code = e.iso2 || SAME_PLACE[e.id];
  const home = (code && countries.find((c) => c.code === code)) || countries.find((c) => c.name === e.name || c.id === e.id);
  if (!home) { unmatched.push(e.name); continue; }
  if (economyOf[home.code]) throw new Error(`two economy cards for ${home.name}: ${economyOf[home.code]} and ${e.id}`);
  economyOf[home.code] = e.id;
}
if (Object.keys(countryOf).length < 190 || Object.keys(economyOf).length < 150) throw new Error(`only ${Object.keys(countryOf).length} countries and ${Object.keys(economyOf).length} economies were indexed`);

const table = (o) => Object.keys(o).sort().map((k) => `  ${k}: ${JSON.stringify(o[k])},`).join("\n");
fs.writeFileSync(
  OUT,
  `/**
 * The country profile and the economy card the site holds for each country,
 * by ISO 3166-1 alpha-2 code: enough to link to either from another page's
 * window without loading the data behind them.
 *
 * GENERATED by build-place-index.cjs — do not edit by hand; re-run it after
 * adding or renaming a country or an economy.
 */

/** Code → the country's id: /dashboard/countries?open=<id> opens its window. */
export const COUNTRY_OF: Record<string, string> = {
${table(countryOf)}
};

/** Code → its economy card's id: /dashboard/economies?open=<id> opens its window. */
export const ECONOMY_OF: Record<string, string> = {
${table(economyOf)}
};

/** An economy card's id → the code of the country it is the economy of. */
export const CODE_OF_ECONOMY: Record<string, string> = Object.fromEntries(Object.entries(ECONOMY_OF).map(([code, id]) => [id, code]));
`,
);
console.log(`wrote ${path.relative(__dirname, OUT)}: ${Object.keys(countryOf).length} countries, ${Object.keys(economyOf).length} economies`);
if (unmatched.length) console.log(`  economy cards with no country profile (not linked): ${unmatched.join(", ")}`);
