#!/usr/bin/env node
/**
 * Builds src/data/countrySlums.ts - the share of each country's city dwellers who live in slums, as asked: UN-Habitat's
 * figures (SDG indicator 11.1.1) as the World Bank publishes them in its World Development Indicators, series
 * EN.POP.SLUM.UR.ZS (CC BY 4.0), from its API with no key.
 *
 * A slum household, as UN-Habitat counts one, lacks one or more of: improved water, improved sanitation, enough living
 * space, durable housing, secure tenure. The share is of the urban population. Each country's latest year; a country the
 * series has no figure for has none here - most high-income countries are not counted.
 *
 *   node build-country-slums.cjs
 */
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const UA = "CommonSphere-build/1.0 (https://commonsphere.vercel.app)";
const OUT = path.join(__dirname, "src/data/countrySlums.ts");
const get = (url) => JSON.parse(execFileSync("curl", ["-sL", "--fail", "--max-time", "120", "-A", UA, url]).toString());

const countries = get("https://api.worldbank.org/v2/country?format=json&per_page=400")[1];
const iso2 = new Map(countries.filter((c) => c.region?.id !== "NA").map((c) => [c.id, c.iso2Code]));
iso2.set("XKX", "XK");
const rows = get("https://api.worldbank.org/v2/country/all/indicator/EN.POP.SLUM.UR.ZS?format=json&per_page=20000&mrnev=1")[1];
const out = {};
for (const r of rows) {
  const cc = iso2.get(r.countryiso3code);
  if (!cc || r.value == null) continue;
  out[cc] = [Number(r.date), Math.round(r.value * 10) / 10];
}
const body = Object.keys(out)
  .sort()
  .map((cc) => `  ${cc}: [${out[cc][0]}, ${out[cc][1]}],`)
  .join("\n");
fs.writeFileSync(
  OUT,
  `/**
 * The share of each country's city dwellers who live in slums: UN-Habitat (SDG 11.1.1), as the World Bank publishes it -
 * World Development Indicators, EN.POP.SLUM.UR.ZS (CC BY 4.0).
 *
 * GENERATED by build-country-slums.cjs - do not edit by hand; change the script and re-run it.
 *
 * By ISO code: [year, % of the urban population]. A household in a slum, as UN-Habitat counts one, lacks one or more of
 * improved water, improved sanitation, enough living space, durable housing and secure tenure.
 */
export const COUNTRY_SLUMS_SOURCE = {
  label: "World Bank — World Development Indicators, EN.POP.SLUM.UR.ZS: population living in slums, % of urban population (UN-Habitat, SDG 11.1.1; CC BY 4.0)",
  url: "https://data.worldbank.org/indicator/EN.POP.SLUM.UR.ZS",
};
export const COUNTRY_SLUMS: Record<string, [year: number, pct: number]> = {
${body}
};
`,
);
console.log(`Slums: ${Object.keys(out).length} countries; years ${[...new Set(Object.values(out).map((v) => v[0]))].sort().join(", ")}`);
