#!/usr/bin/env node
/**
 * Builds src/data/countryMeanIncome.ts - how well off each country's people are on average, as the World Bank's household
 * surveys measure it: the mean income or consumption per person a day, in 2021 dollars at purchasing power parity, from
 * its Poverty and Inequality Platform (CC BY 4.0), read from its API with no key.
 *
 * Each country's latest survey year, the national figure only (never an urban or rural one alone), and never a year the
 * Platform fills in between surveys. Some surveys measure income and some consumption - spending - and the two are kept
 * apart in the file, as the Platform keeps them: consumption runs below income in the same country.
 *
 *   node build-country-mean-income.cjs
 */
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const UA = "CommonSphere-build/1.0 (https://commonsphere.vercel.app)";
const OUT = path.join(__dirname, "src/data/countryMeanIncome.ts");
const get = (url) => JSON.parse(execFileSync("curl", ["-sL", "--fail", "--max-time", "180", "-A", UA, url], { maxBuffer: 256 * 1024 * 1024 }).toString());

const wb = get("https://api.worldbank.org/v2/country?format=json&per_page=400")[1];
const iso2 = new Map(wb.map((c) => [c.id, c.iso2Code]));
iso2.set("XKX", "XK");
const rows = get("https://api.worldbank.org/pip/v1/pip?country=all&year=all&povline=3&fill_gaps=false&ppp_version=2021&format=json");
const best = new Map();
for (const r of rows) {
  if (r.reporting_level !== "national" || r.is_interpolated || r.mean == null) continue;
  const cc = iso2.get(r.country_code);
  if (!cc) continue;
  const was = best.get(cc);
  // The latest year; where a year has both an income and a consumption survey, the one the Platform lists first is kept.
  if (!was || r.reporting_year > was.reporting_year) best.set(cc, r);
}
const body = [...best.keys()]
  .sort()
  .map((cc) => {
    const r = best.get(cc);
    return `  ${cc}: [${r.reporting_year}, ${Math.round(r.mean * 100) / 100}, ${JSON.stringify(/cons/i.test(r.welfare_type) ? "consumption" : "income")}],`;
  })
  .join("\n");
fs.writeFileSync(
  OUT,
  `/**
 * Each country's mean income or consumption per person a day (2021 PPP dollars), from the World Bank's household
 * surveys: Poverty and Inequality Platform (CC BY 4.0).
 *
 * GENERATED by build-country-mean-income.cjs - do not edit by hand; change the script and re-run it.
 *
 * By ISO code: [survey year, dollars a day, what the survey measures]. National figures only, survey years only.
 */
export const COUNTRY_MEAN_INCOME_SOURCE = {
  label: "World Bank — Poverty and Inequality Platform: mean income or consumption per person a day, 2021 PPP (CC BY 4.0)",
  url: "https://pip.worldbank.org/",
};
export const COUNTRY_MEAN_INCOME: Record<string, [year: number, perDay: number, measure: "income" | "consumption"]> = {
${body}
};
`,
);
console.log(`PIP means: ${best.size} countries`);
for (const cc of ["US", "LU", "DE", "IN", "NG", "BR", "CN"]) console.log(cc, JSON.stringify(best.get(cc) && [best.get(cc).reporting_year, best.get(cc).mean, best.get(cc).welfare_type]));
