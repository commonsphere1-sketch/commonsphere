/**
 * Builds supabase/functions/refresh-data/places.ts — the name of every
 * country and territory on the site, keyed by its ISO code, for the news job
 * to recognise in headlines. Generated from src/data/countriesData.ts so the
 * two cannot drift apart; the common forms a headline uses instead
 * ("U.S.", "Britain", "Chinese", "Kyiv") are kept by hand in news.ts.
 *
 *   node build-news-places.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execSync } = require("child_process");

const OUT = path.join(__dirname, "supabase/functions/refresh-data/places.ts");
const bundle = path.join(os.tmpdir(), "commonsphere-news-places.cjs");
execSync(
  `npx esbuild src/data/countriesData.ts --bundle --format=cjs --platform=node --log-level=error --outfile="${bundle}"`,
  { cwd: __dirname, stdio: "inherit" },
);
const { countriesData } = require(bundle);

const rows = countriesData
  .map((c) => [c.code, c.name])
  .sort((a, b) => a[0].localeCompare(b[0]));
if (rows.length < 240) throw new Error(`only ${rows.length} countries`);

fs.writeFileSync(
  OUT,
  `/**
 * Every country and territory on the site, ISO code → name, for the news
 * job to recognise in headlines.
 *
 * GENERATED by build-news-places.cjs on ${new Date().toISOString().slice(0, 10)} from src/data/countriesData.ts
 * — do not edit by hand; re-run the script.
 */
export const COUNTRY_NAMES: [string, string][] = [
${Array.from({ length: Math.ceil(rows.length / 4) }, (_, i) =>
  "  " + rows.slice(i * 4, i * 4 + 4).map(([code, name]) => `[${JSON.stringify(code)}, ${JSON.stringify(name)}],`).join(" "),
).join("\n")}
];
`,
);
console.log(`wrote ${path.relative(__dirname, OUT)}: ${rows.length} places`);
