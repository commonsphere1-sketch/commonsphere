#!/usr/bin/env node
/**
 * Builds src/data/countryLabour.ts - how each country's people work, as the International Labour Organization counts it,
 * as asked: ILOSTAT (CC BY 4.0), read from its data API with no key (https://rplumber.ilo.org/data/indicator/).
 *
 *   SDG_0831_SEX_ECO_RT_A  Informal employment, % of all employment (SDG 8.3.1) - both sexes, all sectors
 *   SDG_0861_SEX_RT_A      Young people 15-24 not in education, employment or training, % (SDG 8.6.1) - both sexes
 *   HOW_TEMP_SEX_NB_A      Average weekly hours actually worked per employed person - both sexes
 *   ILR_TUMT_NOC_RT_A      Trade union density, % of employees
 *   ILR_CBCT_NOC_RT_A      Collective bargaining coverage, % of employees
 *
 * Each country's latest year, from the country's own counts only - its labour force and household surveys, censuses and
 * administrative records - never the ILO's modelled estimates (source "XA") and never a year after this one (a
 * projection). A figure ILOSTAT marks unreliable ("U") is left out.
 *
 *   node build-country-labour.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const UA = "CommonSphere-build/1.0 (https://commonsphere.vercel.app)";
const CACHE = path.join(os.tmpdir(), "commonsphere-ilo");
const OUT = path.join(__dirname, "src/data/countryLabour.ts");
fs.mkdirSync(CACHE, { recursive: true });

/** A CSV's rows, quotes and all. */
function parseCsv(text) {
  const rows = [];
  let row = [],
    cell = "",
    q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') (cell += '"'), i++;
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ",") row.push(cell), (cell = "");
    else if (c === "\n") row.push(cell), rows.push(row), (row = []), (cell = "");
    else if (c !== "\r" && c !== "﻿") cell += c;
  }
  if (cell || row.length) row.push(cell), rows.push(row);
  return rows;
}

function indicator(id) {
  const file = path.join(CACHE, `${id}.csv`);
  if (!(fs.existsSync(file) && Date.now() - fs.statSync(file).mtimeMs < 20 * 3600e3))
    execFileSync("curl", ["-sL", "--fail", "--max-time", "300", "-A", UA, "-o", file, `https://rplumber.ilo.org/data/indicator/?id=${id}&format=.csv&type=code&lang=en`]);
  const rows = parseCsv(fs.readFileSync(file, "utf8"));
  const head = rows[0];
  return rows.slice(1).filter((r) => r.length > 3).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

// This year, by a server's clock (the machine's runs hours fast).
const thisYear = new Date(execFileSync("curl", ["-sI", "--max-time", "60", "https://api.worldbank.org/v2/country"]).toString().match(/^date:\s*(.+)$/im)[1]).getUTCFullYear();
const wb = JSON.parse(execFileSync("curl", ["-s", "-L", "--max-time", "120", "-A", UA, "https://api.worldbank.org/v2/country?format=json&per_page=400"]).toString())[1];
const iso2 = new Map(wb.map((c) => [c.id, c.iso2Code]));
iso2.set("XKX", "XK");
iso2.set("PSE", "PS");
iso2.set("TWN", "TW");

const WANT = [
  ["informal", "SDG_0831_SEX_ECO_RT_A", (r) => r.sex === "SEX_T" && r.classif1 === "ECO_SECTOR_TOTAL"],
  ["neet", "SDG_0861_SEX_RT_A", (r) => r.sex === "SEX_T"],
  ["hours", "HOW_TEMP_SEX_NB_A", (r) => r.sex === "SEX_T"],
  ["union", "ILR_TUMT_NOC_RT_A", () => true],
  ["bargaining", "ILR_CBCT_NOC_RT_A", () => true],
];
const out = {};
const counts = {};
for (const [key, id, take] of WANT) {
  const best = new Map();
  for (const r of indicator(id)) {
    if (!take(r)) continue;
    if (/^XA/.test(r.source ?? "")) continue;
    if (/U/.test(r.obs_status ?? "")) continue;
    const y = +r.time;
    const v = Number(r.obs_value);
    if (!Number.isFinite(y) || y > thisYear || r.obs_value === "" || !Number.isFinite(v)) continue;
    const cc = iso2.get(r.ref_area);
    if (!cc) continue;
    const was = best.get(cc);
    if (!was || y > was[0]) best.set(cc, [y, Math.round(v * 10) / 10]);
  }
  for (const [cc, f] of best) (out[cc] ??= {})[key] = f;
  counts[key] = best.size;
}

const body = Object.keys(out)
  .sort()
  .map((cc) => `  ${cc}: ${JSON.stringify(out[cc])},`)
  .join("\n");
fs.writeFileSync(
  OUT,
  `/**
 * How each country's people work, as the International Labour Organization counts it: ILOSTAT (CC BY 4.0).
 *
 * GENERATED by build-country-labour.cjs - do not edit by hand; change the script and re-run it.
 *
 * Each figure is [year, value]: the country's latest, from its own surveys, censuses or records - never the ILO's
 * modelled estimates, never a projection. A country ILOSTAT holds nothing for has no entry.
 */
export type LabourFigure = [year: number, value: number];
export type CountryLabour = {
  /** Informal employment, % of all employment (SDG 8.3.1). */
  informal?: LabourFigure;
  /** Young people 15-24 not in education, employment or training, % (SDG 8.6.1). */
  neet?: LabourFigure;
  /** Average weekly hours actually worked per employed person. */
  hours?: LabourFigure;
  /** Trade union density, % of employees. */
  union?: LabourFigure;
  /** Collective bargaining coverage, % of employees. */
  bargaining?: LabourFigure;
};
export const COUNTRY_LABOUR_SOURCES = {
  informal: { label: "ILOSTAT — SDG 8.3.1, informal employment (CC BY 4.0)", url: "https://ilostat.ilo.org/data/" },
  neet: { label: "ILOSTAT — SDG 8.6.1, youth not in education, employment or training (CC BY 4.0)", url: "https://ilostat.ilo.org/data/" },
  hours: { label: "ILOSTAT — average weekly hours actually worked per employed person (CC BY 4.0)", url: "https://ilostat.ilo.org/data/" },
  union: { label: "ILOSTAT — trade union density rate (CC BY 4.0)", url: "https://ilostat.ilo.org/topics/union-membership/" },
  bargaining: { label: "ILOSTAT — collective bargaining coverage rate (CC BY 4.0)", url: "https://ilostat.ilo.org/topics/collective-bargaining/" },
};
export const COUNTRY_LABOUR: Record<string, CountryLabour> = {
${body}
};
`,
);
console.log(`ILOSTAT: ${Object.keys(out).length} countries; ${JSON.stringify(counts)}; up to ${thisYear}`);
for (const cc of ["US", "IN", "DE", "BR", "NG", "FR"]) console.log(cc, JSON.stringify(out[cc]));
