/**
 * Which countries' district files do not fit together, measured: the maps cut a country's first-order borders from the
 * edges its districts share (static/geo/admin2), so that the two meet. Where a file's districts do not share their
 * edges - gaps and overlaps between neighbours, as some publishers' tracings have - those borders come out in scraps:
 * Turkmenistan's drew less than half of its velayats' borders.
 *
 * For each country this measures the length of the first-order borders cut from its districts against the length of the
 * same borders in its first-order file (static/geo/admin1, Natural Earth). Where the districts give less than
 * SHARE_MIN of it, the country is listed, and the maps draw its first-order borders from the first-order file and every
 * edge of its districts in full, rather than the scraps. Nothing is drawn that the files do not hold.
 *
 *   node build-admin2-tiling.cjs     (after build-admin2.cjs; then build-admin2-borders.cjs, which reads the list)
 */
const fs = require("fs");
const path = require("path");
const { mesh } = require("topojson-client");

const GEO = path.join(__dirname, "static/geo");
const OUT = path.join(__dirname, "src/data/admin2Untiled.ts");
/** The share of a country's first-order borders its districts must give for their edges to be trusted. */
const SHARE_MIN = 0.9;

/** A line's length in degrees, the east-west part shrunk by the latitude: enough to compare two tracings of one border. */
function length(geom) {
  let s = 0;
  const line = (c) => {
    for (let i = 1; i < c.length; i++) {
      const [x0, y0] = c[i - 1];
      const [x1, y1] = c[i];
      s += Math.hypot((x1 - x0) * Math.cos((((y0 + y1) / 2) * Math.PI) / 180), y1 - y0);
    }
  };
  if (geom?.type === "LineString") line(geom.coordinates);
  else if (geom?.type === "MultiLineString") geom.coordinates.forEach(line);
  return s;
}

const listed = {};
let measured = 0;
for (const f of fs.readdirSync(path.join(GEO, "admin2")).sort()) {
  if (!/^[A-Z]{2}\.json$/.test(f)) continue;
  const one = path.join(GEO, "admin1", f);
  if (!fs.existsSync(one)) continue;
  const t2 = JSON.parse(fs.readFileSync(path.join(GEO, "admin2", f), "utf8"));
  const t1 = JSON.parse(fs.readFileSync(one, "utf8"));
  if (!t2.objects.a) continue;
  const parent = (g) => g.properties && g.properties.p;
  const fromDistricts = length(mesh(t2, t2.objects.a, (a, b) => a !== b && parent(a) !== parent(b)));
  const fromDivisions = length(mesh(t1, t1.objects[Object.keys(t1.objects)[0]], (a, b) => a !== b));
  if (!fromDivisions) continue;
  measured++;
  const share = fromDistricts / fromDivisions;
  if (share < SHARE_MIN) listed[f.slice(0, 2)] = Math.round(share * 100) / 100;
}
if (measured < 150) throw new Error(`only ${measured} countries were measured`);

const TODAY = new Date().toISOString().slice(0, 10);
fs.writeFileSync(
  OUT,
  `/**
 * The countries whose district files do not fit together, by the share of their first-order borders the districts give.
 *
 * GENERATED by build-admin2-tiling.cjs on ${TODAY} — do not edit by hand; change the script and re-run it.
 *
 * Measured over ${measured} countries: the length of the first-order borders cut from the edges a country's districts share
 * (static/geo/admin2, geoBoundaries), against the same borders in its first-order file (Natural Earth). Below
 * ${SHARE_MIN}, the districts do not share their edges and those borders would draw in scraps, so for these the maps draw
 * the first-order borders from the first-order file and every edge of the districts in full.
 */
export const ADMIN2_UNTILED: Record<string, number> = ${JSON.stringify(listed)};
`,
);
console.log(`wrote ${path.relative(__dirname, OUT)}: ${Object.keys(listed).length} of ${measured} countries -`, listed);
