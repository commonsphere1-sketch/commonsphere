/**
 * Builds src/data/economyMarkets.ts — the year-by-year series behind the
 * charts of an economy's window: growth, prices and jobs drawn together, its
 * stock market, and what borrowing costs.
 *
 * All of it is the World Bank's World Development Indicators (CC BY 4.0), by
 * country, from 2000 to the latest year published:
 *
 *   NY.GDP.MKTP.KD.ZG   real GDP growth, % a year
 *   FP.CPI.TOTL.ZG      inflation, consumer prices, % a year
 *   SL.UEM.TOTL.ZS      unemployment, % of the labour force (ILO estimate)
 *   CM.MKT.LCAP.GD.ZS   stock market value: listed domestic companies, % of GDP
 *   CM.MKT.TRAD.GD.ZS   shares traded in the year, % of GDP
 *   CM.MKT.INDX.ZG      S&P Global Equity Indices, change over the year, %
 *   FR.INR.LEND         lending rate, %
 *   FR.INR.RINR         real interest rate, %
 *
 * A year the Bank gives no figure for is left empty - never filled from its
 * neighbours - and a series with fewer than three figures is left out. No
 * government bond yield is here: the Bank publishes none, and no other open
 * source gives one for every country on one footing; the window says so.
 *
 * Nothing is computed. What the window works out from these - a highest and
 * a lowest year, the sum of inflation and unemployment - it says it works
 * out.
 *
 *   node build-economy-markets.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");

const OUT = path.join(__dirname, "src/data/economyMarkets.ts");
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
const CACHE = path.join(os.tmpdir(), "commonsphere-economy-markets");
fs.mkdirSync(CACHE, { recursive: true });

const FROM = 2000;
const SERIES = {
  growth: ["NY.GDP.MKTP.KD.ZG", 1],
  inflation: ["FP.CPI.TOTL.ZG", 1],
  unemployment: ["SL.UEM.TOTL.ZS", 1],
  stockValue: ["CM.MKT.LCAP.GD.ZS", 1],
  stockTraded: ["CM.MKT.TRAD.GD.ZS", 1],
  stockChange: ["CM.MKT.INDX.ZG", 1],
  lendingRate: ["FR.INR.LEND", 2],
  realRate: ["FR.INR.RINR", 2],
};

async function indicator(code) {
  const at = path.join(CACHE, `${code}.json`);
  if (fs.existsSync(at) && Date.now() - fs.statSync(at).mtimeMs < 24 * 3600e3) return JSON.parse(fs.readFileSync(at, "utf8"));
  const rows = [];
  for (let page = 1, pages = 1; page <= pages; page++) {
    const res = await fetch(`https://api.worldbank.org/v2/country/all/indicator/${code}?format=json&per_page=20000&date=${FROM}:2030&page=${page}`, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`World Bank ${code}: HTTP ${res.status}`);
    const j = await res.json();
    if (!Array.isArray(j) || !Array.isArray(j[1])) throw new Error(`World Bank ${code}: no rows`);
    pages = j[0].pages;
    rows.push(...j[1]);
  }
  fs.writeFileSync(at, JSON.stringify(rows));
  return rows;
}

(async () => {
  const meta = await (await fetch("https://api.worldbank.org/v2/country?format=json&per_page=400", { headers: { "User-Agent": UA } })).json();
  const countries = new Set(meta[1].filter((c) => c.region.value !== "Aggregates").map((c) => c.id));
  if (countries.size < 200) throw new Error("World Bank: the list of countries is short");
  const by = {};
  let lastYear = FROM;
  const counted = {};
  for (const [key, [code, dp]] of Object.entries(SERIES)) {
    const rows = await indicator(code);
    const perCountry = new Map();
    for (const r of rows) {
      if (r.value === null || !countries.has(r.countryiso3code)) continue;
      const year = Number(r.date);
      if (!Number.isInteger(year) || year < FROM) continue;
      const m = perCountry.get(r.countryiso3code) ?? new Map();
      m.set(year, Number(Number(r.value).toFixed(dp)));
      perCountry.set(r.countryiso3code, m);
      if (year > lastYear) lastYear = year;
    }
    counted[key] = 0;
    for (const [iso3, m] of perCountry) {
      if (m.size < 3) continue;
      const first = Math.min(...m.keys());
      const last = Math.max(...m.keys());
      const values = [];
      for (let y = first; y <= last; y++) values.push(m.has(y) ? m.get(y) : null);
      (by[iso3] ??= {})[key] = [first, values];
      counted[key]++;
    }
  }
  const today = new Date().toISOString().slice(0, 10);
  const codes = Object.keys(by).sort();
  fs.writeFileSync(
    OUT,
    `/**
 * Growth, prices and jobs, the stock market and the cost of borrowing, year
 * by year, country by country: the series an economy's window draws.
 *
 * GENERATED by build-economy-markets.cjs on ${today} — do not edit by hand; change
 * the script and re-run it.
 *
 * World Bank, World Development Indicators, ${FROM} to ${lastYear}. Each series is
 * [its first year, a figure for each year from then]; a year the Bank gives
 * no figure for is null, and a series with fewer than three figures is
 * absent. Keyed by the country's three-letter code. Countries with a series:
 * ${Object.entries(counted).map(([k, n]) => `${k} ${n}`).join(", ")}.
 */
export const ECONOMY_MARKETS_SOURCE = {
  label: "World Bank — World Development Indicators",
  url: "https://data.worldbank.org/",
  retrieved: "${today}",
  indicators: ${JSON.stringify(Object.fromEntries(Object.entries(SERIES).map(([k, [code]]) => [k, code])))},
};

export type MarketSeries = [from: number, values: (number | null)[]];
export type EconomyMarkets = Partial<Record<${Object.keys(SERIES).map((k) => JSON.stringify(k)).join(" | ")}, MarketSeries>>;

export const ECONOMY_MARKETS: Record<string, EconomyMarkets> = {
${codes.map((c) => `  ${c}: ${JSON.stringify(by[c])},`).join("\n")}
};
`,
  );
  console.log(`wrote ${path.relative(__dirname, OUT)} (${Math.round(fs.statSync(OUT).size / 1024)} KB) · ${codes.length} countries · to ${lastYear}`);
  console.log(`  ${JSON.stringify(counted)}`);
  const us = by.USA;
  console.log(`  USA: ${Object.entries(us).map(([k, [f, v]]) => `${k} ${f}–${f + v.length - 1} last ${v[v.length - 1]}`).join("; ")}`);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
