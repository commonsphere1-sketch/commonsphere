/**
 * Builds src/data/leaderIndex.ts — which leader profiles the World Leaders
 * page holds for each country, so a country's window can link to them.
 *
 * The profiles themselves live in src/pages/WorldleadersPage.tsx, a file far
 * too large to load just to learn whether a country has one. This reads the
 * head of each entry there (id, name, country code, title) and writes a small
 * index beside the other data. It invents nothing and copies nothing but
 * those four fields.
 *
 * The page checks the index against its own list when it loads in
 * development, and says so in the console if this needs running again.
 *
 *   node build-leader-index.cjs
 */
const fs = require("fs");
const path = require("path");

const PAGE = path.join(__dirname, "src/pages/WorldleadersPage.tsx");
const OUT = path.join(__dirname, "src/data/leaderIndex.ts");

const src = fs.readFileSync(PAGE, "utf8").replace(/\r\n/g, "\n");
const start = src.indexOf("const LEADERS: Leader[] = [");
const end = src.indexOf("\n];", start);
if (start < 0 || end < 0) throw new Error("the LEADERS list was not found in the page");
const block = src.slice(start, end);

// The head of an entry, in the order every entry writes it.
const HEAD = new RegExp(
  String.raw`\{\s*id: "([^"]+)",\s*name: "([^"]+)",\s*country: "([^"]+)",\s*countryCode: "([A-Z]{2})",\s*flag: "[^"]*",\s*title:\s*"((?:[^"\\]|\\.)*)"`,
  "g",
);
const byCountry = {};
let found = 0;
for (let m; (m = HEAD.exec(block)); ) {
  found++;
  (byCountry[m[4]] ||= []).push({ id: m[1], name: m[2], title: JSON.parse(`"${m[5]}"`) });
}
// Every entry has one birth year, so the two counts must agree; a miss would silently drop a leader.
const entries = (block.match(/\n    birthYear:/g) || []).length;
if (!found || found !== entries) throw new Error(`read ${found} leaders, but the list holds ${entries}`);

const lines = Object.keys(byCountry)
  .sort()
  .map((code) => `  ${code}: ${JSON.stringify(byCountry[code])},`);
fs.writeFileSync(
  OUT,
  `/**
 * The leader profiles on the World Leaders page, by country: enough to link
 * to one from a country's window without loading the page that holds them.
 *
 * GENERATED by build-leader-index.cjs — do not edit by hand; re-run it after
 * changing the leaders in src/pages/WorldleadersPage.tsx.
 */
export interface LeaderRef {
  /** The profile's id: /dashboard/world-leaders?open=<id> opens it. */
  id: string;
  name: string;
  title: string;
}

/** ISO 3166-1 alpha-2 code → the profiles held for that country, in the page's order. */
export const LEADERS_BY_COUNTRY: Record<string, LeaderRef[]> = {
${lines.join("\n")}
};

export const LEADER_COUNT = ${found};
`,
);
console.log(`wrote ${path.relative(__dirname, OUT)}: ${found} leaders in ${Object.keys(byCountry).length} countries`);
const multi = Object.entries(byCountry).filter(([, v]) => v.length > 1);
if (multi.length) console.log("  more than one: " + multi.map(([c, v]) => `${c} (${v.map((x) => x.name).join(", ")})`).join("; "));
