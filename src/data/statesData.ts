export interface Legislator {
  name: string;
  party: "Democrat" | "Republican" | "Independent";
  termEnd: number; // year
}

export interface Representative {
  name: string;
  party: "Democrat" | "Republican" | "Independent";
  district: string;
}

export interface USState {
  id: string;
  name: string;
  abbreviation: string;
  capital: string;
  region: string;
  population: number;
  gdp: number;
  medianIncome: number;
  unemploymentRate: number;
  approvalRating: number;
  areaKm2: number;
  governor: string;
  party: "Democrat" | "Republican" | "Independent";
  statehood: number;
  crimeIndex: number;
  educationRank: number;
  healthcareRank: number;
  stateTaxRate: number; // top marginal state income tax rate (%)
  salesTaxRate: number; // combined state + avg local sales tax (%)
  minimumWage: number; // state minimum wage ($/hr); 0 = follows federal $7.25
  averageIncome: number; // mean per-capita personal income ($)
  trends: { month: string; gdp: number; employment: number }[];
  // NEW demographic / political / energy fields
  ethnicity: { group: string; pct: number }[];
  landUse: { type: string; pct: number }[];
  ageGroups: { group: string; pct: number }[];
  medianAge: number;
  voterShare: { party: string; pct: number }[];
  wealthPoverty: { label: string; pct: number }[];
  energyMix: { source: string; pct: number }[];
  qualityOfLiving: number; // composite score out of 100 (higher = better QoL)
  senators: Legislator[];
  houseSeats: number; // total House seats for the state
  representatives: Representative[];
}

function makeTrends(
  baseGdp: number,
  baseEmp: number,
): { month: string; gdp: number; employment: number }[] {
  const months = [
    "Jan",
    "Feb",
    "Mar",
    "Apr",
    "May",
    "Jun",
    "Jul",
    "Aug",
    "Sep",
  ];
  return months.map((month, i) => ({
    month,
    gdp: Math.round(baseGdp * (0.96 + i * 0.005)),
    employment: parseFloat((baseEmp - 0.2 + i * 0.04).toFixed(1)),
  }));
}

// Helper builders
function eth(
  white: number,
  black: number,
  hispanic: number,
  asian: number,
  other: number,
) {
  return [
    { group: "White", pct: white },
    { group: "Black", pct: black },
    { group: "Hispanic", pct: hispanic },
    { group: "Asian", pct: asian },
    { group: "Other", pct: other },
  ];
}
function land(
  urban: number,
  agri: number,
  forest: number,
  water: number,
  other: number,
) {
  return [
    { type: "Urban", pct: urban },
    { type: "Agriculture", pct: agri },
    { type: "Forest", pct: forest },
    { type: "Water", pct: water },
    { type: "Other", pct: other },
  ];
}
function age(
  u18: number,
  a1834: number,
  a3554: number,
  a5564: number,
  o65: number,
) {
  return [
    { group: "Under 18", pct: u18 },
    { group: "18–34", pct: a1834 },
    { group: "35–54", pct: a3554 },
    { group: "55–64", pct: a5564 },
    { group: "65+", pct: o65 },
  ];
}
function vote(dem: number, rep: number, ind: number) {
  return [
    { party: "Democrat", pct: dem },
    { party: "Republican", pct: rep },
    { party: "Independent", pct: ind },
  ];
}
function wealth(
  top20: number,
  middle60: number,
  poverty: number,
  extreme: number,
) {
  return [
    { label: "Top 20%", pct: top20 },
    { label: "Middle 60%", pct: middle60 },
    { label: "Near Poverty", pct: extreme },
    { label: "Below Poverty", pct: poverty },
  ];
}
function energy(
  coal: number,
  gas: number,
  nuclear: number,
  hydro: number,
  solar: number,
  wind: number,
  other: number,
) {
  return [
    { source: "Coal", pct: coal },
    { source: "Natural Gas", pct: gas },
    { source: "Nuclear", pct: nuclear },
    { source: "Hydro", pct: hydro },
    { source: "Solar", pct: solar },
    { source: "Wind", pct: wind },
    { source: "Other", pct: other },
  ];
}

