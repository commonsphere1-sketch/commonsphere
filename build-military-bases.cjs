/**
 * Builds src/data/militaryBases.ts — which countries keep military bases
 * abroad and where, for the Military panel of a country's window.
 *
 * What is and is not published. No body publishes a count of every country's
 * bases at home, and none publishes a full register of bases abroad: defence
 * ministries name some, and researchers compile the rest. The fullest open
 * compilation is Wikipedia's "List of countries with overseas military
 * bases" (CC BY-SA 4.0), which goes operating country by operating country
 * and names the countries that host each one's forces, with its sources.
 *
 * This reads that list: for each country with a section, the hosts its
 * tables name with a flag; and, turned round, for each host the countries
 * whose bases it is listed with. It is a list of host countries, not a count
 * of bases - a host may have one facility or dozens - and the page says so.
 * It records nothing for bases at home.
 *
 * A table row that names its host some other way than with a flag template
 * is not read; a country that has a section but no host read is kept as
 * listed, with none named, so the page sends the reader to the list instead
 * of saying there are none.
 *
 *   node build-military-bases.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execSync } = require("child_process");

const OUT = path.join(__dirname, "src/data/militaryBases.ts");
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
const CACHE = path.join(os.tmpdir(), "commonsphere-military-bases");
fs.mkdirSync(CACHE, { recursive: true });
const PAGE = "List_of_countries_with_overseas_military_bases";

/** Wikipedia's name for a country where the site's differs. */
const ALIAS = { Turkey: "Türkiye", "Ivory Coast": "Côte d'Ivoire", "Republic of the Congo": "Congo", "Democratic Republic of the Congo": "DR Congo", "Czech Republic": "Czechia", "The Bahamas": "Bahamas", "The Gambia": "Gambia" };
const NOT_SECTIONS = /^(Background|See also|Notes|References|Further reading|External links)$/i;

function loadCountries() {
  const bundle = path.join(CACHE, "countriesData.cjs");
  execSync(`npx esbuild src/data/countriesData.ts --bundle --format=cjs --platform=node --log-level=error --outfile="${bundle}"`, { cwd: __dirname, stdio: "inherit" });
  delete require.cache[bundle];
  return require(bundle).countriesData;
}

(async () => {
  const at = path.join(CACHE, "list.json");
  if (!fs.existsSync(at)) {
    const res = await fetch(`https://en.wikipedia.org/w/api.php?action=parse&format=json&formatversion=2&prop=wikitext|revid&redirects=1&page=${PAGE}`, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`Wikipedia: HTTP ${res.status}`);
    fs.writeFileSync(at, await res.text());
  }
  const parsed = JSON.parse(fs.readFileSync(at, "utf8")).parse;
  const text = parsed.wikitext;

  const countries = loadCountries();
  const codeOf = new Map(countries.map((c) => [c.name.toLowerCase(), c.code]));
  const code = (name) => codeOf.get((ALIAS[name] ?? name).toLowerCase()) ?? null;

  const abroad = {};
  const hosted = {};
  const unread = [];
  for (const part of text.split(/\n(?===[^=])/)) {
    const h = /^==\s*([^=]+?)\s*==/.exec(part);
    if (!h || NOT_SECTIONS.test(h[1])) continue;
    const operator = code(h[1]);
    if (!operator) {
      unread.push(h[1]);
      continue;
    }
    const hosts = [];
    for (const row of part.split(/\n\|-/).slice(1)) {
      const m = /\{\{\s*(?:flag|flagcountry|flagu)\s*\|\s*([^}|]+)/i.exec(row);
      if (!m) continue;
      const host = m[1].trim();
      // An alliance or a territory that is not one of the site's places is named as the list names it.
      if (/^(NATO|EU|UN)$/i.test(host)) continue;
      if (!hosts.includes(host)) hosts.push(host);
    }
    abroad[operator] = hosts;
    for (const host of hosts) {
      const hc = code(host);
      if (hc && hc !== operator) (hosted[hc] ||= []).push(countries.find((c) => c.code === operator).name);
    }
  }
  const n = Object.keys(abroad).length;
  if (n < 12 || !abroad.US || abroad.US.length < 20 || !abroad.JP?.includes("Djibouti")) throw new Error(`the list reads wrong: ${n} operating countries, United States in ${abroad.US?.length} hosts`);

  const today = new Date().toISOString().slice(0, 10);
  const q = (v) => JSON.stringify(v);
  fs.writeFileSync(
    OUT,
    `/**
 * Which countries keep military bases abroad, and where: the host countries
 * Wikipedia's list names for each.
 *
 * GENERATED by build-military-bases.cjs on ${today} — do not edit by hand;
 * change the script and re-run it.
 *
 * It is a list of host countries, not a count of bases: a host may have one
 * facility or dozens. No body publishes a count of every country's bases at
 * home or a full register of those abroad, and the site does not make one.
 */
export const MILITARY_BASES_SOURCE = {
  label: "Wikipedia — List of countries with overseas military bases (CC BY-SA 4.0)",
  url: "https://en.wikipedia.org/wiki/${PAGE}",
  /** The revision of the article that was read. */
  revision: ${parsed.revid ?? "null"},
  retrieved: "${today}",
};

/** For a country the list has a section for: the hosts its tables name, as the list names them. An empty list is a section whose hosts could not be read. Keyed by ISO code. */
export const BASES_ABROAD: Record<string, string[]> = {
${Object.entries(abroad).map(([c, h]) => `  ${c}: ${q(h)},`).join("\n")}
};

/** For a host: the countries whose bases the list places in it. Keyed by ISO code. */
export const BASES_HOSTED: Record<string, string[]> = {
${Object.entries(hosted).map(([c, h]) => `  ${c}: ${q([...new Set(h)].sort())},`).join("\n")}
};
`,
  );
  console.log(`wrote ${path.relative(__dirname, OUT)}: ${n} operating countries, ${Object.keys(hosted).length} hosts; revision ${parsed.revid}`);
  for (const [c, h] of Object.entries(abroad)) console.log(`  ${c}: ${h.length} - ${h.slice(0, 10).join(", ")}${h.length > 10 ? "…" : ""}`);
  if (unread.length) console.log(`  sections not matched to a country: ${unread.join(", ")}`);
  console.log(`  hosted, e.g. DJ: ${hosted.DJ?.join(", ")}; DE: ${hosted.DE?.join(", ")}`);
})().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
