/**
 * Builds src/data/developmentStatus.ts — the country lists behind the world
 * map's "Global North" and "Global South" scopes.
 *
 * "Global North" and "Global South" are not official categories and no body
 * publishes a membership list for them, so this does not invent one. It uses
 * the published classification that comes closest and carries ISO codes: the
 * UN Statistics Division's M49 standard, whose "Developed / Developing
 * Countries" column splits every country and area in two. UNSD states that
 * these designations are for statistical convenience and do not express a
 * judgement about the stage a country has reached in the development process,
 * and the page that uses these lists says so.
 *
 * The M49 table repeats each country once per region grouping, so codes are
 * de-duplicated and any code classified two different ways is reported rather
 * than silently resolved.
 *
 *   node build-development-status.cjs
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execSync } = require("child_process");

const SOURCE_URL = "https://unstats.un.org/unsd/methodology/m49/overview/";
const OUT = path.join(__dirname, "src/data/developmentStatus.ts");
const CACHE = path.join(os.tmpdir(), "country-reference-cache");
const UA = "commonsphere-data-build/1.0 (+https://github.com/commonsphere1-sketch/commonsphere)";
fs.mkdirSync(CACHE, { recursive: true });

function loadCountries() {
  const bundle = path.join(CACHE, "countriesData.cjs");
  execSync(`npx esbuild src/data/countriesData.ts --bundle --format=cjs --platform=node --log-level=error --outfile="${bundle}"`, { cwd: __dirname, stdio: "inherit" });
  delete require.cache[bundle];
  return require(bundle).countriesData;
}

const cells = (row) =>
  [...row.matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/gi)].map((m) =>
    m[1].replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/\s+/g, " ").trim(),
  );

(async () => {
  const cached = path.join(CACHE, "m49.html");
  let html;
  if (fs.existsSync(cached)) {
    html = fs.readFileSync(cached, "utf8");
  } else {
    const res = await fetch(SOURCE_URL, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`M49: HTTP ${res.status}`);
    html = await res.text();
    fs.writeFileSync(cached, html);
  }

  const rows = html.split(/<tr[^>]*>/i).slice(1).map(cells);
  const header = rows[0];
  const iCode = header.findIndex((c) => /alpha-?2/i.test(c));
  const iStatus = header.findIndex((c) => /developed\s*\/\s*developing/i.test(c));
  const iName = header.findIndex((c) => /country or area/i.test(c));
  if (iCode < 0 || iStatus < 0 || iName < 0) throw new Error("M49 columns not found; the table layout changed");

  const status = new Map(); // code -> { status, name }
  const conflicts = [];
  let blank = 0;
  for (const r of rows.slice(1)) {
    const code = (r[iCode] || "").trim().toUpperCase();
    const s = (r[iStatus] || "").trim();
    if (!/^[A-Z]{2}$/.test(code)) continue;
    if (s !== "Developed" && s !== "Developing") { blank++; continue; }
    const seen = status.get(code);
    if (seen && seen.status !== s) conflicts.push(`${code}: ${seen.status} vs ${s}`);
    if (!seen) status.set(code, { status: s, name: r[iName] });
  }
  if (conflicts.length) throw new Error("M49 classifies a code two ways: " + conflicts.join("; "));

  const north = [...status.entries()].filter(([, v]) => v.status === "Developed").map(([c]) => c).sort();
  const south = [...status.entries()].filter(([, v]) => v.status === "Developing").map(([c]) => c).sort();

  // What this means for the dataset the map actually draws.
  const countries = loadCountries();
  const inNorth = countries.filter((c) => north.includes(c.code));
  const inSouth = countries.filter((c) => south.includes(c.code));
  const unclassified = countries.filter((c) => !status.has(c.code));

  const today = new Date().toISOString().slice(0, 10);
  const list = (arr) => arr.map((c) => `"${c}"`).join(", ");
  fs.writeFileSync(OUT, `import { countriesData, type Country } from "./countriesData";

/**
 * Global North and Global South, as the world map uses them.
 *
 * GENERATED by build-development-status.cjs on ${today} — do not edit by hand;
 * change the script and re-run it.
 *
 * Neither term is an official category and no body publishes a membership
 * list, so these are not invented here. They are the UN Statistics Division's
 * M49 "Developed / Developing Countries" classification, the published split
 * that carries ISO codes. UNSD notes that the designations are for statistical
 * convenience and do not express a judgement about the stage a country or area
 * has reached in the development process; the map says so where it offers
 * these scopes.
 *
 * Of the ${countries.length} countries in this dataset: ${inNorth.length} are classified developed,
 * ${inSouth.length} developing, and ${unclassified.length} are not classified by M49${unclassified.length ? ` (${unclassified.map((c) => c.name).join(", ")})` : ""}.
 * Unclassified countries belong to neither scope and are drawn as out of scope,
 * rather than assigned to one.
 */
export const DEVELOPMENT_STATUS_SOURCE = {
  label: "UN M49 — developed / developing classification",
  url: "${SOURCE_URL}",
  retrieved: "${today}",
};

/** M49 "Developed" — ${north.length} countries and areas. */
export const GLOBAL_NORTH_CODES = [${list(north)}] as const;

/** M49 "Developing" — ${south.length} countries and areas. */
export const GLOBAL_SOUTH_CODES = [${list(south)}] as const;

const northSet = new Set<string>(GLOBAL_NORTH_CODES);
const southSet = new Set<string>(GLOBAL_SOUTH_CODES);

export function isGlobalNorth(country: Country): boolean {
  return northSet.has(country.code);
}

export function isGlobalSouth(country: Country): boolean {
  return southSet.has(country.code);
}

export const globalNorthCountries: Country[] = countriesData.filter(isGlobalNorth);
export const globalSouthCountries: Country[] = countriesData.filter(isGlobalSouth);
`);

  console.log(`M49: ${status.size} codes classified (${north.length} developed, ${south.length} developing); ${blank} rows without a classification`);
  console.log(`dataset: ${inNorth.length} north, ${inSouth.length} south, ${unclassified.length} unclassified`);
  if (unclassified.length) console.log("  unclassified:", unclassified.map((c) => `${c.code} ${c.name}`).join(", "));
  console.log("north sample:", inNorth.slice(0, 8).map((c) => c.name).join(", "));
  console.log("south sample:", inSouth.slice(0, 8).map((c) => c.name).join(", "));
  console.log(`wrote ${path.relative(__dirname, OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });
